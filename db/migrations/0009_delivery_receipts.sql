-- Квитанции о доставке: второй конец того же состояния, что и прочтение.
--
-- Доставлено и прочитано - две величины одного состояния, а не два
-- независимых счётчика. Порознь они разрешают положение "прочитано больше,
-- чем доставлено": клиент объявил прочтение раньше, чем получение, и
-- отправитель увидел состояние, которого не было. Поэтому оба номера
-- приходят одним запросом и записываются одной операцией.
--
-- По устройствам строки не разводятся. Доставлено, если хотя бы одно
-- устройство получило; прочитано, если хотя бы одно прочитало до этого
-- номера. Это ровно максимум присланных значений, а максимум - одна
-- строка на пользователя, то есть уже существующая.
--
-- Имена в базе и в API отличаются одним словом, и это осознанно: наружу
-- уходит `read_seq` - что сообщило устройство, - а хранится `last_read_seq`:
-- максимум сообщённого. Так же устроена пара `messages.conversation_seq`
-- и `Message.seq`.

ALTER TABLE read_states
    ADD COLUMN last_delivered_seq bigint NOT NULL DEFAULT 0;

-- Приведение существующих строк. По умолчанию ноль, но ноль был бы
-- утверждением, которого никто не проверял: строка с `last_read_seq = 495`
-- и нулевой доставкой нарушает отношение в момент своего появления, и
-- ограничение это подтвердит. Прочитанное получено, поэтому доставка
-- подтягивается к прочтению, а не наоборот: обратное движение отняло бы
-- у пользователя уже показанное.
--
-- Миграция не опирается на то, что сегодня строк нет. Пустая таблица -
-- обстоятельство, а не свойство схемы, и закладывать его в миграцию значит
-- оставить в ней утверждение, которое перестанет быть верным молча.
UPDATE read_states
SET last_delivered_seq = last_read_seq
WHERE last_delivered_seq < last_read_seq;

-- NOT VALID по ADR 0006: добавление ограничения не должно сканировать
-- таблицу под исключительной блокировкой. Затем VALIDATE - отдельным
-- оператором, который берёт SHARE UPDATE EXCLUSIVE и записи не останавливает.
--
-- Пара нужна именно вместе. NOT VALID в одиночку проверяет только новые и
-- изменённые строки: возможность невозможной строки остаётся открытой ровно
-- там, где её не видно, - в данных, лежащих с прошлого года. VALIDATE
-- превращает "мы уверены, что таких строк нет" в проверенный факт.
ALTER TABLE read_states
    ADD CONSTRAINT read_states_read_le_delivered
    CHECK (last_read_seq <= last_delivered_seq) NOT VALID;

ALTER TABLE read_states
    VALIDATE CONSTRAINT read_states_read_le_delivered;
