-- Идентификатор сессии Keycloak рядом с нашим.
--
-- Проверено на живом Keycloak 26.7: `sid` в токене — не UUID, а короткая
-- непрозрачная строка вида `cyt4SLGLVN3jRXGVyhAs5aAG`. Спецификация OIDC
-- так и говорит: `sid` — строка, а не UUID; предположение, что там UUID,
-- держалось ровно до первого настоящего входа.
--
-- Колонка `session_id` остаётся UUID и остаётся нашей: она выводится
-- из внешнего значения детерминированно (uuid5), поэтому таблицы
-- соответствия не нужно, а повторный вход по-прежнему попадает в ту же
-- строку. Сырое значение хранится рядом ради разбора инцидентов: без него
-- «какая сессия Keycloak» выясняется обратным перебором, то есть никак.
--
-- Колонка допускает NULL намеренно: у строк, заведённых до этой миграции,
-- внешнего значения нет, а `SET NOT NULL` — это полное сканирование под
-- блокировкой (ADR 0006).
--
-- Индекса нет: по этой колонке не ищут. Поиск идёт по `session_id`,
-- который вычисляется из внешнего значения за наносекунды.

ALTER TABLE sessions ADD COLUMN external_session_id text;

COMMENT ON COLUMN sessions.external_session_id IS
    'Непрозрачный sid из токена Keycloak; session_id выведен из него через uuid5';
