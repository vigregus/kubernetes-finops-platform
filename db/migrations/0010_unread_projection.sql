-- Проекция непрочитанного и чекпойнт потребителя.
--
-- Обе таблицы производные, и это не оговорка, а причина, по которой их
-- можно завести: источник истины — messages и read_states, и обе
-- восстанавливаются из него целиком. Проекция нужна не ради истины, а
-- ради цены чтения: список бесед читается на каждый вход, и COUNT по
-- messages на каждую беседу списка — то самое усиление чтения, ради
-- устранения которого эта таблица и заводится.
--
-- Чекпойнт — один на беседу, а не на пару (пользователь, беседа), и это
-- решение с доводом. Для последовательности 10 (B->A), 11 (A->B),
-- 12 (B->A) чекпойнт пользователя A, сдвигаемый только по чужим
-- сообщениям, увидел бы в 12 "потерянный 11" — хотя 11 собственное
-- сообщение A и непрочитанное не увеличивает. Поэтому чекпойнт двигается
-- любым message.created, а признак "чужое" применяется только к +1.
--
-- BEGIN/COMMIT в файле не пишутся: транзакцией владеет db/migrate.sh.
--
-- CREATE INDEX здесь нет намеренно. Оба первичных ключа объявлены внутри
-- CREATE TABLE, а доступа, требующего индекса сверх первичного, у этих
-- таблиц не бывает: список бесед читает префикс ключа проекции, замок
-- берётся по первичному ключу смещений, а записи идут точными ключами.
-- Отсюда следствие, которое стоит держать в голове: правило
-- "CREATE INDEX обязан быть CONCURRENTLY" и противоречие с
-- psql --single-transaction этот файл не трогает — обходить его нечем,
-- потому что обходить нечего.

-- ---------------------------------------------------------------------------
-- Проекция: сколько непрочитанного у пользователя в беседе
-- ---------------------------------------------------------------------------

CREATE TABLE unread_projection (
    user_id         uuid        NOT NULL REFERENCES users (user_id),
    conversation_id uuid        NOT NULL REFERENCES conversations (conversation_id),
    unread_count    bigint      NOT NULL DEFAULT 0,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    -- Порядок колонок ключа не произвольный: префикс по user_id — это
    -- ровно тот доступ, который нужен списку бесед ("счётчики бесед
    -- одного пользователя"). Обратный порядок обслуживал бы пересборку
    -- по беседе, но ей поиск по conversation_id не нужен: состав беседы
    -- известен из conversation_members, и строки пишутся точными ключами.
    PRIMARY KEY (user_id, conversation_id),
    -- Ограничение объявлено здесь, а не отдельным ADD CONSTRAINT, и это
    -- не только вопрос удобства: таблица на момент создания пуста, поэтому
    -- проверять нечего и NOT VALID с последующим VALIDATE не требуются.
    -- Отрицательный счётчик — не "маловероятное значение", а признак
    -- того, что приращение и абсолютная запись разошлись.
    CONSTRAINT unread_projection_not_negative CHECK (unread_count >= 0)
);

-- ---------------------------------------------------------------------------
-- Чекпойнт: до какого номера беседы потребитель применил события
-- ---------------------------------------------------------------------------

CREATE TABLE unread_offsets (
    conversation_id     uuid PRIMARY KEY REFERENCES conversations (conversation_id),
    -- Наибольший применённый conversation_seq. Ноль означает "не применено
    -- ничего", и это не особый случай: беседа, чьё первое увиденное событие
    -- имеет номер 1, разрыва не обнаружит.
    applied_through_seq bigint      NOT NULL DEFAULT 0,
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT unread_offsets_not_negative CHECK (applied_through_seq >= 0)
);
