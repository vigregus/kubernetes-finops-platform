-- Производные непрочитанного уходят вместе с беседой.
--
-- Находка живого прогона, а не заготовка. С появлением `unread_projection`
-- уборка интеграционных проверок перестала проходить: `receipts_check.py`
-- упал на `ForeignKeyViolationError`, удаляя беседу, которую производная
-- держала внешним ключом. Довести это до конца можно было двумя способами,
-- и выбран не тот, что проще для проверок.
--
-- Проекция и чекпойнт - производные дочерние данные беседы: они теряют
-- смысл вместе с ней, и смысла переживать её у них нет. Заставлять каждую
-- проверку, удаляющую беседу, помнить о таблицах непрочитанного значило бы
-- размазать знание об одной зависимости по чужим файлам - и сломаться снова
-- на следующей производной таблице. Каскад объявляет зависимость там, где
-- она заведена.
--
-- Каскад объявлен только по беседе, и это не симметрия ради краткости.
-- У пользователя нормальный путь удаления - стирание (`0002_erasure.sql`,
-- снятый NOT NULL и надгробие), а не физический `DELETE`. Отсутствие
-- каскада по `user_id` сохраняет защиту от случайного физического удаления
-- пользователя, на которого опирается история; появившийся каскад по беседе
-- её не отменяет - он срабатывает только там, где беседа удаляется явно.
--
-- NOT VALID -> VALIDATE по ADR 0006 и образцу `0009`: добавление
-- ограничения не должно сканировать таблицу под исключительной
-- блокировкой, а проверка существующих строк идёт отдельным шагом.
-- Для внешнего ключа правило ADR не формулируется - оно написано про
-- `CHECK`, - но дисциплина здесь одна, и пара нужна целиком: `NOT VALID`
-- в одиночку проверяет только новые строки, а расхождение остаётся ровно
-- там, где его не видно. `VALIDATE` берёт SHARE UPDATE EXCLUSIVE и записи
-- не останавливает.
--
-- BEGIN/COMMIT в файле не пишутся: транзакцией владеет db/migrate.sh.

-- ---------------------------------------------------------------------------
-- Проекция: не переживает беседу
-- ---------------------------------------------------------------------------

ALTER TABLE unread_projection
    DROP CONSTRAINT unread_projection_conversation_id_fkey;

ALTER TABLE unread_projection
    ADD CONSTRAINT unread_projection_conversation_id_fkey
    FOREIGN KEY (conversation_id)
    REFERENCES conversations (conversation_id)
    ON DELETE CASCADE
    NOT VALID;

ALTER TABLE unread_projection
    VALIDATE CONSTRAINT unread_projection_conversation_id_fkey;

