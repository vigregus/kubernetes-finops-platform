-- Журнал стираний перестаёт быть источником истины.
--
-- Ошибка предыдущей миграции: `erasure_log` лежал в той же базе, которую
-- восстанавливают из копии. Восстановление откатывает его вместе с данными,
-- то есть о стираниях, случившихся после даты копии, узнать неоткуда —
-- механизм не мог исполнить собственное обещание.
--
--   1 сентября    копия
--   5 сентября    пользователь стёрт, запись в erasure_log
--   10 сентября   восстановление из копии от 1 сентября
--                 → erasure_log тоже откатился, стирание потеряно
--
-- Источником истины становится внешнее долговечное хранилище с собственным
-- жизненным циклом (объектное, версионированное, вне единицы восстановления
-- базы). Таблица остаётся локальным индексом и очередью на подтверждение.

-- Стирание не считается завершённым, пока запись не подтверждена внешним
-- журналом. До этого completed_at остаётся пустым, и пользователю нельзя
-- отвечать, что данные удалены.
ALTER TABLE erasure_log ADD COLUMN ledger_confirmed_at timestamptz;

-- Адрес записи во внешнем журнале: ключ объекта и версия. Без версии
-- подтверждение недоказуемо — объект по тому же ключу мог быть перезаписан.
ALTER TABLE erasure_log ADD COLUMN ledger_object_key text;
ALTER TABLE erasure_log ADD COLUMN ledger_version_id text;

-- Завершённость и подтверждение — одно и то же событие. Разъехавшись,
-- они дают ровно тот отказ, ради которого миграция и написана:
-- «стёрли» в базе без следа во внешнем журнале.
ALTER TABLE erasure_log ADD CONSTRAINT erasure_completed_requires_ledger CHECK (
    completed_at IS NULL
    OR (ledger_confirmed_at IS NOT NULL
        AND ledger_object_key IS NOT NULL
        AND ledger_version_id IS NOT NULL)
);

-- Очередь на подтверждение: по этому индексу писатель журнала находит
-- стирания, о которых внешнее хранилище ещё не знает.
CREATE INDEX erasure_log_unconfirmed_idx
    ON erasure_log (requested_at) WHERE ledger_confirmed_at IS NULL;

COMMENT ON TABLE erasure_log IS
    'Локальный индекс стираний. Источник истины — внешний журнал; '
    'при восстановлении из копии читается он, а не эта таблица.';
