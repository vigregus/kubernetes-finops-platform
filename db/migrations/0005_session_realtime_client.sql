-- Идентификатор realtime-соединения рядом с сессией.
--
-- Centrifugo v6 генерирует идентификатор соединения сам (`uuid.NewRandom()`)
-- и возвращает его клиенту в ответе на подключение. Задать его заранее нельзя:
-- в команде connect поля `client` нет, а в centrifuge-js нет опции, которая
-- бы его передавала. Поэтому `session_id` не годится в роли идентификатора
-- соединения — это разные UUID из разных пространств.
--
-- Чтобы отзыв сессии мог разорвать ровно это соединение, клиент после
-- подключения сообщает свой `client` через `POST /realtime/connections`,
-- и он ложится сюда. Колонка NULL намеренно: сессия могла не подключаться
-- к realtime вовсе, или клиент не успел сообщить идентификатор. Тогда
-- принудительный разрыв невозможен, но отзыв в Postgres и HTTP-отказ уже
-- отрезали доступ — разрыв соединения это ускорение, а не условие.
--
-- Колонка допускает NULL без NOT NULL по той же причине, что
-- `external_session_id`: у строк, заведённых до миграции, значения нет,
-- а `SET NOT NULL` — это полное сканирование под блокировкой (ADR 0006).
--
-- Индекса нет: по этой колонке не ищут. Поиск идёт по `session_id`,
-- а `realtime_client_id` читается тем же `UPDATE ... RETURNING`, которым
-- сессия отзывается.

ALTER TABLE sessions ADD COLUMN realtime_client_id text;

COMMENT ON COLUMN sessions.realtime_client_id IS
    'Идентификатор соединения Centrifugo, сообщённый клиентом; по нему отзыв рвёт ровно это соединение';
