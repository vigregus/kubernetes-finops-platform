-- Присутствие: «был в сети» переживает потерю эфемерного состояния.
--
-- Две половины одного понятия, и они намеренно в разных хранилищах. «Онлайн»
-- живёт в realtime_connections и по построению теряется: соединения заводит
-- Centrifugo, а он о разрыве не сообщает вовсе — ни прокси disconnect, ни
-- события на отключение у него нет. Поэтому единственный authoritative
-- признак жизни — время: соединение живо, пока refreshed_at попадает в окно
-- (см. domain/presence.py). «Был в сети» — факт в Postgres, и он переживает
-- и перезапуск Centrifugo, и смерть уборщика.
--
-- Появившаяся колонка заодно закрывает долг: UserSummary.last_seen_at
-- объявлен контрактом (packages/contracts/openapi.yaml) и не отдавался,
-- потому что брать значение было неоткуда, — это и было записано в
-- докстринге api/main.py.
--
-- BEGIN/COMMIT в файле не пишутся: транзакцией владеет db/migrate.sh.
--
-- CREATE INDEX здесь нет намеренно — по той же причине, что и в
-- 0010_unread_projection.sql. Правило ADR 0006 «CREATE INDEX обязан быть
-- CONCURRENTLY» и `psql --single-transaction` в db/migrate.sh противоречат
-- друг другу (CONCURRENTLY внутри транзакции не работает), обойти это нечем,
-- а расширять список GRANDFATHERED — значит обходить правило. Поэтому
-- вопрос не «как построить индекс», а «зачем он», и ответ на него такой:
--
--   * таблица ограничена по построению, а не по объёму трафика. В ней лежат
--     только соединения внутри окна живости — их убирает уборщик, — поэтому
--     строк в ней порядка одновременных соединений (не истории за сутки);
--   * агрегат `count(DISTINCT user_id) ... WHERE refreshed_at >= ...` читает
--     всё окно целиком и ведущей колонкой `user_id` не пользуется: индекс
--     `(user_id, refreshed_at)` ему не помог бы, а уборка по свежести идёт
--     по той же таблице, которая и есть содержимое окна;
--   * цена была бы не нулевой: `refreshed_at` обновляется на каждом
--     продлении (раз в ~120 с на соединение, services/realtime.py), а
--     обновление колонки в ключе индекса — это не-HOT запись, то есть
--     переписывание индекса на каждое подтверждение жизни;
--   * и главное: запроса, которому индекс нужен, сегодня не существует.
--     Возврат к «есть ли свежее соединение у этого пользователя» (онлайн
--     собеседников) — это G3-007, и индекс заводится вместе с ним.

-- ---------------------------------------------------------------------------
-- Последнее подтверждённое время жизни пользователя
-- ---------------------------------------------------------------------------

-- NULL — не «давно», а «ни разу»: отметка проставляется первым же
-- подтверждённым соединением. Умолчания `now()` здесь нет намеренно —
-- оно выдало бы любому существующему профилю «был в сети» в момент
-- применения миграции, то есть выдумало бы факт, которого не было.
--
-- Отметка монотонна: пишется как GREATEST(прежнее, now()) в той же
-- транзакции, что и upsert соединения (repositories/users.py). Присваивание
-- вместо GREATEST теряло бы время при встречных продлениях двух устройств
-- одного человека: проигравшая гонка записала бы более старое значение.
ALTER TABLE users ADD COLUMN last_seen_at timestamptz;

COMMENT ON COLUMN users.last_seen_at IS
    'Последнее подтверждённое соединение пользователя; NULL - не был ни разу';
