/**
 * Минимальная лента — наблюдаемая поверхность, а не оформление.
 *
 * Здесь нет ни пузырей, ни аватаров, ни надгробий: штатный дизайн
 * (`MessageTimeline` и его соседи) остаётся проектным запасом и подключится
 * вместе с отправкой. Гейт доказывает **поведение**, и разметке этой ленты
 * предстоит быть заменённой, не тронув ни одного редьюсера.
 *
 * Поэтому разметка несёт ровно четыре вещи, и все четыре — предмет приёмки (B8):
 *
 * * `data-applied-through-seq` — применённая граница беседы. По ней видно и
 *   догрузку, и её завершение, а без неё сходимость пришлось бы читать по
 *   человекочитаемой строке;
 * * `data-message-id` — по нему доказывается «ровно один раз»;
 * * `data-message-seq` — по нему доказывается «строго возрастает на 1». Без
 *   второго атрибута последовательность из DOM недоказуема: идентификаторы
 *   уникальны, но не упорядочены;
 * * `data-message-state` — состояние **своего** сообщения по квитанции
 *   собеседника (`read`/`delivered`/`sent`). У чужого сообщения атрибута нет
 *   вовсе: состояние доставки — утверждение о том, что стало с моим письмом, а
 *   чужое уже здесь, и «доставлено» про него сказало бы то, чего собеседник не
 *   делал. Нет атрибута и тогда, когда квитанции не было: `undefined` — это
 *   «сервер о доставке не сообщал», и рисовать вместо него состояние значило бы
 *   вывести его из молчания.
 *
 * Порядок элементов **не наводится здесь**: лента приходит из `eventMerge`,
 * единственной точки сортировки и дедупликации (B22). Сортировка тут завела бы
 * второе место ровно для того, что уже закрыто, — и разошлась бы с первым молча.
 *
 * Пустота ленты различается **по границе, а не по длине массива**. Пустой массив
 * до снимка значит «сервер ещё не отвечал», после пустого снимка — «сервер
 * ответил, и в беседе ноль сообщений». Это два разных факта, и первый из них
 * пустым состоянием не является: показать там «No messages yet. Say hello to …»
 * значило бы вывести утверждение о беседе из молчания сервера.
 *
 * ## Видимость строк — источник второго числа квитанции
 *
 * `onVisibleThroughSeq` сообщает **максимум по строкам, видимым целиком**, и
 * это единственный источник «прочитано». `document.visibilityState` отвечает на
 * вопрос о вкладке, а не о сообщении: в ленте `1…500` при окне `450…470`
 * сообщение `500` уже в DOM, вкладка видима — и `read_seq = 500` было бы
 * утверждением, которого человек не делал.
 *
 * Три названные цены, и все три — не случайность, а граница выбранного
 * определения:
 *
 * * **наблюдателя может не быть вовсе** (jsdom, старый браузер) — тогда колбэк
 *   не зовётся ни разу, и квитанция просто не отправляется. Молчание честнее
 *   падения панели, и это проверяется юнитом с подставленным наблюдателем, а не
 *   отсутствием наблюдателя;
 * * **строка выше окна не станет «видимой целиком» никогда** — её отношение
 *   пересечения не дойдёт до единицы. Сообщение, которое не помещается на
 *   экран, прочитать нельзя по определению, и `read` такое сообщение не
 *   покроет;
 * * **отчитаться можно только о строках, которые есть в DOM** — и потому
 *   `read` не опережает `delivered`: это тот же инвариант, а не совпадение.
 */
import { useEffect, useRef } from "react"

import { EmptyConversationState } from "./EmptyConversationState"
import type { ChatMessage } from "../../../shared/lib/types"

interface MessageListProps {
  /** Отсортированные по `seq` сообщения беседы. */
  messages: readonly ChatMessage[]
  /**
   * Нужно только пустой ленте: пустое состояние называет беседу по имени.
   *
   * Пустота выбирается **внутри** ленты, а не вместо неё, потому что граница
   * применяется и к пустой беседе тоже: `{"items": []}` — успешный снимок с
   * границей `0` (B23). Замени ленту на пустое состояние снаружи — и атрибут
   * границы исчез бы ровно там, где он равен нулю, то есть «пустая беседа»
   * и «снимка ещё не было» стали бы в разметке неразличимы.
   */
  conversationName: string
  /**
   * Применённая граница: `null` — **неизвестна**, снимка ещё не было.
   *
   * `null` и `0` здесь разные вещи, и различать их обязательно. `0` —
   * подтверждённый пустой снимок, после которого первое сообщение (`seq = 1`)
   * применяется, а не читается пропуском. `null` — «мы ещё не знаем», и
   * выдать его за ноль значило бы объявить факт, которого нет.
   *
   * Разница видна в разметке: при `null` атрибута нет вовсе, при `0` он есть
   * и равен нулю. Атрибут со значением «неизвестно» был бы тем же самым, что
   * `0`, только хуже — приёмке пришлось бы знать про него отдельно.
   */
  appliedThroughSeq: number | null
  /**
   * Максимум по целиком видимым строкам — и только при **изменении**.
   *
   * Сообщается номер, а не «прочитано всё»: решение о том, отправлять ли
   * квитанцию (и не отстала ли она от уже отправленного), принимает
   * `features/receipts/useReceipts.ts`, а лента отвечает ровно на один вопрос —
   * какая строка сейчас видна целиком.
   */
  onVisibleThroughSeq?: (seq: number) => void
}

export function MessageList({
  messages,
  conversationName,
  appliedThroughSeq,
  onVisibleThroughSeq,
}: MessageListProps) {
  const scroller = useRef<HTMLDivElement | null>(null)

  /**
   * Номера строк, видимых целиком прямо сейчас, и наибольший уже сообщённый.
   *
   * Множество, а не одно число: строка может уйти из окна, и тогда максимум
   * обязан быть пересчитан по оставшимся, а не храниться как «последний
   * увиденный». Второе число — память о сообщённом: повтор той же границы
   * стоил бы запроса квитанции на каждый кадр прокрутки.
   */
  const visible = useRef<Set<number>>(new Set())
  const reported = useRef(0)

  useEffect(() => {
    const root = scroller.current
    if (root === null || onVisibleThroughSeq === undefined) return
    // Наблюдателя может не быть вовсе — и это не ошибка, а названная цена
    // (D13): панель обязана отрисоваться, а квитанция в этом случае просто не
    // отправляется.
    if (typeof IntersectionObserver === "undefined") return

    const seen = visible.current

    const observer = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          const seq = Number(entry.target.getAttribute("data-message-seq"))
          // Условие повторяет опцию `threshold` намеренно. Опция — это то, о
          // чём мы просим браузер; условие — то, на что мы отвечаем, и оно
          // обязано быть здесь: полагаться на одно лишь уведомление значило бы
          // принять «пересекается» за «видна целиком» — ровно то, что D13
          // запрещает. Проверяется это двойником: часть опций он повторить не
          // может, а отношение пересечения называет сам.
          if (entry.isIntersecting && entry.intersectionRatio >= 1) {
            seen.add(seq)
          } else {
            seen.delete(seq)
          }
        }

        if (seen.size === 0) return
        const max = Math.max(...seen)
        if (max <= reported.current) return

        reported.current = max
        onVisibleThroughSeq(max)
      },
      // `root` — сам контейнер ленты: без него отсчёт шёл бы от окна браузера,
      // а лента живёт в своей прокрутке.
      { root, threshold: 1.0 },
    )

    for (const row of root.querySelectorAll("[data-message-seq]")) observer.observe(row)

    return () => observer.disconnect()
  }, [messages, onVisibleThroughSeq])

  return (
    <div
      ref={scroller}
      className="flex min-h-0 flex-1 flex-col overflow-y-auto px-6 py-4"
      data-applied-through-seq={appliedThroughSeq ?? undefined}
    >
      {messages.length > 0 ? (
        messages.map((message) => (
          <div
            key={message.id}
            data-message-id={message.id}
            data-message-seq={message.seq}
            data-message-state={
              message.authorId === "me" ? message.deliveryState : undefined
            }
            className="py-1 text-sm"
          >
            {message.text}
          </div>
        ))
      ) : appliedThroughSeq === null ? (
        // Пустая лента до снимка — не «сообщений нет», а «ответа ещё не было».
        // Различие здесь не косметическое: `EmptyConversationState` говорит
        // «No messages yet. Say hello to …» — утверждение о беседе, которое
        // выводилось бы из молчания сервера. Тот же класс, что «Active now» и
        // «Last seen» в шапке, и та же цена: правдоподобно ровно до тех пор,
        // пока беседа не окажется непустой.
        //
        // Пустая панель без объяснения тоже не годится: она неотличима от
        // сломанной разметки, а `ConnectionStatusLine` в этот момент говорит о
        // соединении, а не об истории. Иконка пустого состояния здесь не
        // рисуется — приглашение «Say hello» было бы тем же утверждением,
        // только картинкой.
        <div className="flex flex-1 flex-col items-center justify-center px-6 text-center">
          <p className="text-sm text-text-warm-secondary">Loading messages…</p>
        </div>
      ) : (
        <EmptyConversationState name={conversationName} />
      )}
    </div>
  )
}
