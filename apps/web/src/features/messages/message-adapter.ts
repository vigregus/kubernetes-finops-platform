/**
 * Таблица соответствия `Message` → `ChatMessage` — **одна запись**, и только она.
 *
 * Отдельный модуль, а не `items.map(...)` на месте вызова, по трём причинам.
 *
 * **Зритель видит себя.** `sender_id` — идентификатор из домена, а модель
 * различает свои и чужие сообщения словом `"me"` (`MessageBubble.tsx:75`:
 * `authorId === "me"` выбирает выравнивание и цвет пузыря). Значит сравнение с
 * `currentUserId` — часть таблицы соответствия, а не деталь рендера: без него
 * свои сообщения приехали бы как входящие, и заметил бы это не компилятор,
 * а человек.
 *
 * **Чего сервер не сказал — того интерфейс не утверждает.** Отсюда
 * `authorName` и `avatarUrl` — `undefined`: `Message` отдаёт только `sender_id`,
 * имени отправителя в ответе нет вовсе (`openapi.yaml:812-833`), а взять его
 * неоткуда — список участников читается другим запросом, которого G3-006 не
 * делает. Пустая подпись честнее выдуманной.
 *
 * **Форма ответа — не здесь.** Этот модуль ничего не сортирует, не фильтрует и
 * не решает, что считать пропуском. Порядок и дедупликация — `eventMerge.ts`
 * (единственная точка того и другого, B22), форма страницы
 * (`items`/`has_more`/`next_after_seq`) — `history.ts`. Здесь только
 * соответствие полей одной записи, и добавление сюда сортировки завело бы
 * второе место ровно для того, что уже закрыто.
 */

import type { Attachment as AttachmentDto, Message as MessageDto } from "../../api/generated"
import type {
  AttachmentKind,
  ChatMessage,
  MessageAttachment,
  MessageKind,
} from "../../shared/lib/types"
import { formatConversationTimestamp, type TimestampFormatOptions } from "../conversations/formatTimestamp"

/**
 * Тип сообщения → вид, который умеет нарисовать интерфейс.
 *
 * `image`/`file`/`voice` — все три `attachment`: модель различает виды вложения
 * внутри `MessageAttachment`, а `kind` отвечает только на вопрос «текст это или
 * вложение».
 *
 * `system` попадает в `unsupported` наравне со всем неизвестным, и это не
 * отговорка: рендера служебных сообщений («Анна добавила Марка») в интерфейсе
 * нет ни одного, а выдать служебную запись за текстовое сообщение значило бы
 * показать её текст как чью-то реплику. `unsupported` и есть честный ответ:
 * «это сообщение интерфейс показать не умеет».
 */
const KIND_OF_TYPE: Readonly<Record<string, MessageKind>> = {
  text: "text",
  image: "attachment",
  file: "attachment",
  voice: "attachment",
}

/** Чего интерфейс не умеет — то `unsupported`, а не «наверное текст». */
const UNSUPPORTED_KIND: MessageKind = "unsupported"

/**
 * Вид вложения — по `content_type`, единственному факту о файле в ответе.
 *
 * По типу сообщения его брать нельзя, даже когда он известен: тип описывает
 * сообщение целиком, а вид вложения читается из самого вложения, и у сообщения
 * с одним вложением это одно и то же значение только по совпадению.
 */
function attachmentKindOf(contentType: string): AttachmentKind {
  if (contentType.startsWith("image/")) return "image"
  if (contentType.startsWith("audio/")) return "voice"
  return "file"
}

/**
 * Имя вложения, когда сервер его не назвал.
 *
 * `Attachment` имени файла не отдаёт вовсе — ни `file_name`, ни `name` в
 * контракте нет, только `content_type` и `size_bytes` (`openapi.yaml:851-853`).
 * Значит подставляется название **вида**, а не выдуманное имя: «Photo» не
 * утверждает, что файл звался `photo.png`, и не выдаёт себя за имя из
 * метаданных.
 *
 * Слова те же, что у превью в списке бесед (`conversations/adapter.ts`,
 * `TYPE_PREVIEW`), и «Voice message» — то же, что у запаса ленты
 * (`mock-data.ts:180`). Повтор здесь назван, а не умолчан: вынести общий словарь
 * в один модуль — правка чужого закрытого файла G3-005, и это долг, а не
 * незамеченная мелочь.
 */
const ATTACHMENT_NAME: Readonly<Record<AttachmentKind, string>> = {
  image: "Photo",
  file: "File",
  voice: "Voice message",
}

const SIZE_UNITS = ["B", "KB", "MB", "GB"] as const

/**
 * Размер файла — **display-строка**, а не число байт.
 *
 * Поле модели называется `sizeLabel` и рисуется в пузыре вложения безусловно
 * (`AttachmentBubble.tsx:51`): прокинутый `size_bytes` дал бы там `2516582`
 * посреди человеческого текста — визуально сломанный дизайн, которого никто не
 * заказывал. Ровно та же ловушка, что у времени в списке бесед, и лечится так
 * же. Сам факт при этом серверный: округление — это перевод, а не догадка.
 */
function sizeLabelOf(bytes: number): string {
  let value = bytes
  let unit = 0
  while (value >= 1024 && unit < SIZE_UNITS.length - 1) {
    value /= 1024
    unit += 1
  }
  // Байты не дробятся: «512.0 B» — это точность, которой у измерения нет.
  const rounded = unit === 0 ? value : Math.round(value * 10) / 10
  return `${rounded} ${SIZE_UNITS[unit]}`
}

/**
 * Вложение → модель. Одно, потому что и модель держит одно.
 *
 * Ответ несёт массив (`attachments?`), а `ChatMessage.attachment` — одиночное
 * поле, и расхождение разбирается здесь, а не в рендере: берётся первый
 * элемент. Это названо, а не выведено: «первое значимое» было бы выбором по
 * смыслу, которого у нас нет, а склейка нескольких в одно — выдумыванием
 * модели на ходу. Несколько вложений в сообщении — дизайн G3-007; до него
 * второго элемента в ответе и не бывает, потому что отправки вложений из
 * браузера в этом гейте нет (B3).
 *
 * Состояние — `ready`, и обоснование у него отдельное, потому что это
 * единственное поле здесь, за которым нет прямой серверной величины.
 */
function attachmentOf(dto: MessageDto, attachment: AttachmentDto): MessageAttachment {
  const kind = attachmentKindOf(attachment.contentType)

  return {
    kind,
    name: ATTACHMENT_NAME[kind],

    /**
     * `state: "ready"` — это **не** «мы знаем, что проверка прошла», а «нет
     * известных незавершённых состояний», и разница здесь несёт смысл.
     *
     * Состояния модели — это состояния *отправки* (`03-v1-scope.md`:
     * uploading → processing → ready, или rejected/failed), то есть жизненный
     * цикл файла, который вкладка прямо сейчас отправляет. У сообщения из
     * истории такого цикла нет:
     *
     * * `uploading` — чисто клиентское состояние (файл лежит в памяти этой
     *   вкладки); отправки из браузера в G3-006 нет вовсе (B3), поэтому из
     *   истории оно недостижимо по построению;
     * * `rejected` и `failed` — состояния отказа отправки; сообщение, дошедшее
     *   до коммита, отказа не получило;
     * * остаётся `processing` — и вот его от `ready` отличить **нечем**:
     *   признака проверки в серверном `Attachment` нет вовсе
     *   (`openapi.yaml:851-853` — `attachment_id`, `content_type`,
     *   `size_bytes`, `download_url`). Нарисовать здесь спиннер «Checking
     *   file…» значило бы утверждать проверку, о которой сервер молчал, и
     *   рисовать её вечно.
     *
     * Поэтому когда у сервера появится признак состояния, читать его надо
     * будет ровно здесь — это единственная строка, которую придётся тронуть.
     */
    state: "ready",

    // Ссылка — предподписанная и с ограниченным сроком, то есть годится для
    // показа и не годится для хранения. В поле модели она попадает как есть:
    // другого адреса у клиента нет, а выдумать постоянный он не может.
    url: attachment.downloadUrl,

    // Длительность приходит в миллисекундах, а модель и пузырь считают в
    // секундах. Усечение, а не округление: 14.8 с — это четырнадцать секунд
    // звука, и `formatDuration` в пузыре всё равно усекает — второй раз
    // округлять вверх значило бы показывать секунду, которой не слышно.
    durationSeconds:
      typeof dto.payload?.durationMs === "number" ? Math.floor(dto.payload.durationMs / 1000) : undefined,

    sizeLabel: sizeLabelOf(attachment.sizeBytes),
  }
}

/**
 * Публикация приходит из сети, поэтому «объект ли это» — первая проверка, а не
 * подробность: `null.message_id` уронил бы обработчик публикации, а падение
 * внутри него уносит соединение.
 *
 * Отдаётся наружу, потому что входов из сети стало **два**: к публикации канала
 * беседы добавилось событие личного канала (`conversations/unreadOverlay.ts`).
 * Второй такой же проверки, написанной по месту, здесь не заводится: она
 * разошлась бы с этой ровно так же, как любой второй экземпляр правила.
 */
export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null
}

/**
 * `"me"` — слово модели, `currentUserId` — идентификатор домена. Перевод здесь,
 * а не в компоненте: рендер не обязан знать, кто смотрит.
 *
 * Функция, а не выражение на месте, потому что входов в модель теперь два —
 * история и канал, — и ответ на вопрос «чьё это сообщение» обязан быть один.
 * Разошедшись, они показали бы свои сообщения входящими ровно на одном из двух
 * путей, и заметил бы это человек, а не компилятор.
 */
function authorIdOf(senderId: string, currentUserId: string): string {
  return senderId === currentUserId ? "me" : senderId
}

/**
 * `now` — обязательный параметр, а не `new Date()` внутри, по той же причине,
 * что и у списка бесед: со скрытыми часами тест на «сегодня/вчера/раньше»
 * зависел бы от момента прогона и не проверял бы ничего.
 *
 * `timestampOptions` — локаль и зона; по умолчанию берутся у браузера. Параметр
 * существует для проверки: без него вывод зависел бы от зоны машины, на
 * которой идёт прогон.
 */
export function adaptMessage(
  dto: MessageDto,
  currentUserId: string,
  now: Date,
  timestampOptions: TimestampFormatOptions = {},
): ChatMessage {
  const kind = KIND_OF_TYPE[dto.type] ?? UNSUPPORTED_KIND
  const first = dto.attachments?.[0]

  return {
    id: dto.messageId,
    seq: dto.seq,

    authorId: authorIdOf(dto.senderId, currentUserId),

    // Имени отправителя в ответе нет — и выдуманного не появляется.
    authorName: undefined,
    avatarUrl: undefined,

    kind,

    // Текст отдаётся всякий раз, когда сервер его прислал, независимо от вида:
    // у вложения он подпись, у текстового сообщения — тело. Что из этого
    // рисовать, решает `kind`, а не адаптер.
    //
    // Сообщение без `payload` даёт `undefined`, а не падение и не подставное
    // слово: «Message» в пузыре было бы выдуманным телом сообщения — в списке
    // бесед такое слово уместно (там строка обязана быть непустой и описывает
    // вид), а в пузыре оно выдаёт себя за содержимое, которого сервер не
    // присылал.
    text: dto.payload?.text,

    // Вид берётся из типа сообщения — это утверждение сервера, — а не из
    // наличия массива: сообщение `image` без вложения остаётся вложением,
    // и понижать его до текста значило бы показать картинку как пустую
    // реплику. `attachment` при этом пуст, и это видно в модели.
    attachment: first === undefined ? undefined : attachmentOf(dto, first),

    // Display-строка, а не ISO: поле рисуется безусловно, и прокинутый
    // `created_at` уехал бы в пузырь как `2026-09-20T14:22:31Z`. Форматтер
    // берётся у списка бесед, а не пишется второй: разошедшиеся форматы дали бы
    // «14:22» в списке и «2:22 PM» в ленте на одной и той же отметке.
    timestamp: formatConversationTimestamp(dto.createdAt, now, timestampOptions) ?? "",

    // Надгробие — признак, а не отсутствие текста: содержимое сервер уже стёр,
    // и повторять это правило здесь незачем — рисование надгробия уже
    // различается по флагу (`MessageTimeline.tsx:43`).
    deleted: dto.deletedAt != null,

    // `deliveryState` не выставляется, и это не пропуск. Квитанции — G3-007;
    // все состояния доставки, кроме клиентских (`sending`/`retrying`/`failed`),
    // требуют ответа сервера о доставке и прочтении, которого этот ответ не
    // несёт. Вывести «прочитано» из того, что сообщение лежит в истории,
    // значило бы нарисовать галочку, которой никто не ставил.
  }
}

/** Страница истории → модели: та же запись, применённая ко всем элементам. */
export function adaptMessages(
  items: readonly MessageDto[],
  currentUserId: string,
  now: Date,
  timestampOptions: TimestampFormatOptions = {},
): ChatMessage[] {
  return items.map((dto) => adaptMessage(dto, currentUserId, now, timestampOptions))
}

/**
 * Публикация канала → модель. Второй вход в ту же таблицу соответствия, и
 * разбор здесь **защитный**, а не доверчивый: форма измерена, а не предположена.
 *
 * `_client_event` (`services/realtime_delivery.py:43-56`) отдаёт ровно пять
 * полей — `type`, `message_id`, `seq`, `sender_id`, `payload` — и публикует их
 * на `conversation:{conversation_id}`. **Привязка к беседе — это подписка**:
 * `conversation_id` в теле публикации не едет вовсе, и брать его оттуда неоткуда.
 *
 * Контракт канала (`packages/contracts/websocket/channels.json`,
 * `$defs.conversationEvent`) обязательным объявляет **только `type`**; поля
 * `message_id`/`seq`/`sender_id`/`payload` у него необязательны, а сам `type`
 * берётся из набора `message.created`/`message.read`/`message.deleted`. Значит
 * разбор обязан отвечать `null`, а не падать: падение внутри обработчика
 * публикации уносит соединение, которого этот гейт и добивается.
 *
 * Чего здесь **не** выводится — и это не пропуски, а названные границы:
 *
 * * **`timestamp`** — на провод не уезжает ни `created_at`, ни иное время.
 *   Подставить момент получения значило бы выдать время прихода за время
 *   отправки, и тем правдоподобнее, чем свежее сообщение. Пустая строка честнее
 *   и ровно так же пуста, как у записи истории, которой сервер времени не назвал.
 * * **`attachment`** — публикация несёт `payload`, а `attachments` живут в ответе
 *   REST (`MessageDto`) и в канал не попадают. Вложение, отправленное живьём,
 *   доедет подписью и **без** вложения; это граница канала, и её закрывает G3-007.
 * * **`kind`** — вида сообщения в публикации нет: `type` здесь — тип **события**
 *   (`message.created`), а не тип сообщения. `"text"` описывает то, что канал
 *   действительно принёс (тело); `unsupported` утверждал бы, что интерфейс не
 *   умеет показать сообщение, которое он тут же и показывает.
 * * **`deleted`** — `false`, и это факт, а не умолчание: надгробия приходят
 *   событием `message.deleted`, на котором ниже стоит `null`.
 * * **`deliveryState`** — по той же причине, что и в истории: `message.created`
 *   сообщает о создании, а не о доставке или прочтении (квитанции — G3-007).
 */
export function adaptPublication(event: unknown, currentUserId: string): ChatMessage | null {
  // Только `message.created` — сообщение. `message.read` и `message.deleted`
  // принадлежат другим возможностям (квитанции, надгробия — G3-007), и нарисовать
  // их репликой значило бы показать чужое событие как текст.
  if (!isRecord(event) || event.type !== "message.created") return null

  const id = event.message_id
  const seq = event.seq
  const senderId = event.sender_id

  // Номер — это и порядок, и признак пропуска, то есть предмет всего гейта:
  // запись без него некуда поставить. Дробный номер тоже отвергается — он не
  // совпал бы ни с одной границей, и `2.5 > 1 + 1` прочиталось бы пропуском.
  if (typeof id !== "string" || id.length === 0) return null
  if (typeof seq !== "number" || !Number.isInteger(seq) || seq < 1) return null

  // Отправитель отличает свою реплику от чужой, опознание доказывает «ровно один
  // раз» (RT-004). Пустая строка на месте любого из них была бы выдуманным
  // значением, а не отсутствием, поэтому запись не применяется вовсе.
  if (typeof senderId !== "string" || senderId.length === 0) return null

  const payload = event.payload

  return {
    id,
    seq,
    authorId: authorIdOf(senderId, currentUserId),
    kind: "text",
    // Тело берётся, когда оно строка: `payload` необязателен, а `payload.text`
    // может прийти числом или объектом. Выдуманного тела не появляется —
    // `undefined` рисуется пустотой.
    text: isRecord(payload) && typeof payload.text === "string" ? payload.text : undefined,
    attachment: undefined,
    timestamp: "",
    deleted: false,
  }
}
