/**
 * Таблица соответствия `GET /me` → модель пользователя.
 *
 * Рукописный `CurrentUser` и `Me` описывают разное, и без названного
 * соответствия разницу закрывают догадкой. Самая дорогая догадка здесь —
 * вывести интерфейс прямо из `capabilities`: возможность есть — рисуем кнопку.
 * Но `capabilities` — это **факт авторизации**, а не обещание, что функция уже
 * реализована: G3-005 не умеет начинать беседы, значит кнопки новой беседы не
 * будет и при `start_conversation` в списке. Интерфейс, ведущий в отказ, хуже
 * отсутствующего.
 */
import type { Me } from "../../api/generated";
import type { CurrentUser } from "../../shared/lib/types";

/**
 * Возможность, как её называет контракт.
 *
 * Выведено из `Me`, а не выписано вторым списком: свой union разошёлся бы с
 * контрактом молча, тогда как здесь шестнадцатая возможность в `openapi.yaml`
 * приходит сюда сама.
 */
export type Capability = Me["capabilities"][number];

/**
 * Зритель: модель пользователя и его возможности — **порознь**.
 *
 * `capabilities` намеренно не поле `user`: возможность не свойство человека, а
 * разрешение на действие, и она живёт до тех пор, пока сервер её отдаёт.
 * Сложенные вместе, они рано или поздно превратились бы в признак вроде
 * `canStartConversation`, то есть в интерфейс, нарисованный из авторизации.
 */
export interface Viewer {
  readonly user: CurrentUser;
  readonly capabilities: readonly Capability[];
}

export function adaptMe(dto: Me): Viewer {
  // `Me.email` типизирован как `string | undefined`, и `null` в тип не входит.
  // Но это **замер** закреплённого генератора, а не обещание контракта: в
  // `openapi.yaml` поле помечено `nullable: true` — единственный 3.0-изм в
  // документе 3.1, — и свернуть `null` сегодня умеет конвертер, а не сам тип.
  // Смена версии генератора возвращает `null` сюда, поэтому приведение названо
  // явно, а не спрятано за необязательным полем.
  const email = dto.email as string | null | undefined;

  return {
    user: {
      name: dto.displayName,
      // Пустая строка — тоже отсутствие адреса: она проходит через тип и дошла
      // бы до интерфейса как «адрес есть, он пустой».
      email: email === undefined || email === null || email === "" ? undefined : email,
      emailVerified: dto.emailVerified,
    },
    capabilities: dto.capabilities,
  };
}
