/**
 * Отправка квитанции: единственное место, где решается, **что** и **когда** уходит.
 *
 * Правила приёма и отображения живут в чистом `receiptWatermarks.ts`; здесь —
 * три вещи, которым нужны таймеры, документ и сеть: дребезг, `visibilitychange`
 * и сам запрос. Ни одно из чисел здесь не пересчитывается: `read` приходит из
 * наблюдателя строк (`MessageList`, D13), `delivered` — из применённой границы
 * ленты (`eventMerge`), и оба уже посчитаны.
 *
 * ## Два числа живут по разным законам (D6)
 *
 * `delivered` — свойство **устройства**: публикация доходит и применяется и в
 * свёрнутой вкладке (таймеры там тормозятся, но JS исполняется). `read` —
 * свойство **взгляда**: он существует только у видимой вкладки. Отсюда четыре
 * клетки, и каждая — отдельное поведение, а не оттенок одного:
 *
 * | Состояние вкладки | `delivered_seq` | `read_seq` |
 * | --- | --- | --- |
 * | `visible`, сообщение применено | растёт | не двигается (строка ниже сгиба) |
 * | `visible`, строка целиком в окне | растёт | растёт |
 * | `hidden`, сообщение применено | **растёт** | **не двигается** |
 * | `hidden` → `visible` | — | уходит свёрнутое |
 *
 * Утверждение «в фоне отправок нет» было бы **ложным** и прошло бы зелёным на
 * дефекте: запрет отправок в фоне отнял бы у `RCP-001` половину смысла, потому
 * что тогда вкладка, объявляющая прочитанным всё применённое, честно меньшего
 * сообщить не может. Поэтому в фоне `read` не «откладывается», а не
 * **отправляется**: `wanted.readSeq` там равен нулю, и «свёрнутое» число уходит
 * на возврате — то, что накопилось за отсутствие, а не первое число после него.
 *
 * ## Возвращается отправленное, а не отправляемое
 *
 * Разметка несёт `data-my-read-seq` (§6), и это **утверждение о том, что вкладка
 * сообщила**, а не о том, что она видит. Поэтому из двух полей остаются только
 * отправленные и подтверждённые транспортом: ноль в `read_seq` означал бы
 * «прочитано ни до чего», то есть утверждение, которого никто не делал, — то же
 * `absence ≠ zero`, что у `unreadCount` и `read_states`. Отсюда две формы одного
 * числа: для сравнения (`receiptToSend`) нужен полный порядок и ноль как дно, а
 * для разметки — отсутствие поля. Перевод между ними один (`outgoingOf`) и
 * опирается на правило, проверяемое мутацией: `receiptToSend` шлёт поле только
 * строго больше уже отправленного, а начинается всё с нуля — значит отправленное
 * поле всегда не меньше единицы, и «ноль» безошибочно читается как «не
 * отправляли».
 *
 * ## Отказ транспорта не отменяет записанное
 *
 * Запрос без гарантий: число записывается как отправленное **только** после
 * ответа, иначе отказ уронил бы вкладку в состояние «я это сообщила», ничего не
 * сообщив. Очереди при этом нет и не нужно: отправляемое число — **максимум**
 * положения вкладки, поэтому следующий повод несёт его же, а не только
 * приращение. Это то же свойство, на котором стоит сверка при возврате (D11):
 * истину приносит чтение, а событие лишь ускоряет.
 */

import { useEffect, useRef, useState } from "react"

import { advance, receiptToSend } from "./receiptWatermarks"
import type { OutgoingReceipt, Watermarks } from "./receiptWatermarks"

/**
 * Дребезг: публикации приходят пачками (догрузка ленты, серия сообщений), и
 * запрос на каждую из них сообщил бы о прочтении чаще, чем человек читал.
 * Величина короткая намеренно — это не «собираем пачку», а «не шлём дважды за
 * один кадр прокрутки»; на сходимость вкладок она не влияет, потому что истину
 * приносит REST (D11), а не скорость квитанции.
 */
const RECEIPT_DEBOUNCE_MS = 250

/** Транспорт квитанции — ровно та операция, что объявлена контрактом. */
export type SendReceipt = (
  conversationId: string,
  receipt: OutgoingReceipt,
) => Promise<unknown>

export interface UseReceiptsOptions {
  readonly conversationId: string
  /**
   * Применённая граница беседы (`eventMerge`); `null` — снимка ещё не было.
   *
   * `null` здесь не ноль: отправить `{delivered_seq: 0}` значило бы объявить
   * доставку, о которой сервер ещё не отвечал.
   */
  readonly deliveredThroughSeq: number | null
  /** Максимум по целиком видимым строкам — единственный источник «прочитано». */
  readonly visibleThroughSeq: number
  /**
   * Отправка. Обязана быть **устойчивой** (модуль или `useCallback`): её смена
   * перезапускает дребезг, и нестабильная ссылка откладывала бы отправку на
   * каждом рендере.
   */
  readonly send: SendReceipt
  readonly debounceMs?: number
}

/**
 * Квитанция вкладки: возвращает то, что **отправлено и подтверждено**, либо
 * `null`, если не отправлено ничего.
 */
export function useReceipts(options: UseReceiptsOptions): OutgoingReceipt | null {
  const {
    conversationId,
    deliveredThroughSeq,
    visibleThroughSeq,
    send,
    debounceMs = RECEIPT_DEBOUNCE_MS,
  } = options

  /**
   * Отправленное — в полном порядке (ноль = дно), для сравнения с желаемым.
   *
   * `useRef`, а не состояние: значение нужно эффекту в момент срабатывания
   * таймера, и перерисовка от его изменения не требуется — разметке служит
   * второе представление ниже.
   */
  const sent = useRef<Watermarks | null>(null)

  /** Отправленное в форме разметки: поля, которой не отправляли, в ней нет. */
  const [sentReceipt, setSentReceipt] = useState<OutgoingReceipt | null>(null)

  /**
   * Видимость вкладки — **состояние**, а не чтение документа в момент отправки.
   *
   * Возврат вкладки обязан **разбудить** отправку: `read` вырос, пока вкладка
   * была в фоне, и без перерисовки на `visibilitychange` отправлять его было бы
   * некому — таймер истёк ещё в фоне, а новых поводов не появилось.
   */
  const [tabVisible, setTabVisible] = useState(() => document.visibilityState !== "hidden")

  useEffect(() => {
    const onVisibilityChange = () => setTabVisible(document.visibilityState !== "hidden")
    document.addEventListener("visibilitychange", onVisibilityChange)
    return () => document.removeEventListener("visibilitychange", onVisibilityChange)
  }, [])

  useEffect(() => {
    const wanted: Watermarks = {
      // Прочтения в фоне не существует: не «отложено», а не отправлено.
      readSeq: tabVisible ? visibleThroughSeq : 0,
      deliveredSeq: deliveredThroughSeq ?? 0,
    }

    if (receiptToSend(sent.current ?? ZERO, wanted) === null) return

    const timer = setTimeout(() => {
      // Пересчёт внутри таймера, а не снаружи: до его срабатывания успевает
      // пройти отправка, и посчитанное заранее поле ушло бы второй раз.
      const pending = receiptToSend(sent.current ?? ZERO, wanted)
      if (pending === null) return

      void send(conversationId, pending).then(
        () => {
          const applied = advance(sent.current, pending)
          sent.current = applied

          // `null` здесь недостижим: `pending` собран `receiptToSend`, а тот
          // пустого запроса не возвращает, — и `advance` без чисел состояния не
          // заводит. Проверка стоит ради типа, а не ради случая, и она не
          // прячет дефект: если бы сюда попало пустое, отправленное осталось бы
          // прежним, а следующая отправка понесла бы те же числа снова.
          if (applied !== null) setSentReceipt(outgoingOf(applied))
        },
        // Отказ транспорта: число не записывается как отправленное, и следующий
        // повод понесёт его снова (см. докстринг модуля). Молча — потому что
        // показать это в интерфейсе нечем, а ретрай уже назначен следующим
        // изменением границы; отказ виден метрикой публикаций на сервере.
        () => undefined,
      )
    }, debounceMs)

    return () => clearTimeout(timer)
  }, [conversationId, tabVisible, visibleThroughSeq, deliveredThroughSeq, send, debounceMs])

  return sentReceipt
}

/** Дно порядка: отправленного ещё нет — но сравнение требует чисел, не `null`. */
const ZERO: Watermarks = { readSeq: 0, deliveredSeq: 0 }

/**
 * Отправленное — в форму разметки.
 *
 * Ноль здесь читается как «не отправляли» безошибочно: поле попадает в запрос
 * только строго большим уже отправленного (см. `receiptToSend`), а начинается
 * всё с нуля, — значит отправленное поле всегда не меньше единицы.
 */
function outgoingOf(sent: Watermarks): OutgoingReceipt {
  return {
    ...(sent.readSeq > 0 ? { readSeq: sent.readSeq } : {}),
    ...(sent.deliveredSeq > 0 ? { deliveredSeq: sent.deliveredSeq } : {}),
  }
}
