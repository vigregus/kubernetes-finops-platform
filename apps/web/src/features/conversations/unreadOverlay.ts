/**
 * Число непрочитанного: разбор события личного канала и его слияние со списком.
 *
 * Модуль чистый — входами и выходами, без сети и без React, — и это не
 * стилистика. Число непрочитанного приходит **двумя** путями: событием
 * `unread.changed` (быстро, best-effort) и ответом `GET /conversations` (медленно,
 * но истина). Правило, по которому одно накладывается на другое, обязано быть
 * проверяемым без браузера: у него есть ровно два свойства, и оба — предмет
 * мутаций (`D11`).
 *
 * **Событие несёт абсолютное число.** Клиент **ставит** его, а не прибавляет:
 * публикация best-effort и повтор доставки возможен (пачка Kafka приезжает
 * второй раз), поэтому «прибавить пришедшее» сдвинуло бы счётчик на каждом
 * повторе. По той же причине накопительным не бывает и оверлей целиком.
 *
 * **Сверка заменяет, а не правит.** Ответ REST кладётся на место события, а не
 * складывается с ним: потерянная публикация («запись прошла, события нет» —
 * названный штатный сценарий `D11`) накоплением не чинится вовсе, а заменой
 * чинится целиком. Это то же правило, что у `last_read_seq`: событие двигает
 * вперёд, истину приносит чтение.
 */
import type { Conversation } from "../../shared/lib/types"
import { isRecord } from "../messages/message-adapter"

/** Событие личного канала, приведённое к модели: какая беседа и сколько. */
export interface UnreadChange {
  readonly conversationId: string
  readonly unreadCount: number
}

/**
 * `unread.changed` → пара «беседа, число» либо `null`.
 *
 * Оба поля в схеме **необязательны** (`channels.json`, `$defs.userEvent`:
 * `required` там один — `type`), и это требование аддитивности, а не мера
 * осторожности. Разрешать — не то же, что принимать: событие без беседы
 * или без числа не имеет смысла, и `null` означает «события нет».
 *
 * Подставить недостающее нулём **нельзя**: `0` — уверенное «прочитано всё»,
 * то есть утверждение, которого сервер не делал, и оно откатило бы счётчик на
 * экране. Ровно тот же класс, что запрещён в `message.read` (`D12`).
 *
 * **Лишнее поле событие не отбрасывает.** `additionalProperties` в схеме нет
 * намеренно: расширение события будущей версией (скажем, `read_at`) обязано
 * приниматься старым клиентом — это и есть `CTR-003`. Поэтому здесь читаются
 * только объявленные имена, а о существовании прочих ключей разбор не знает
 * вовсе; отказ из-за незнакомого ключа превратил бы безобидное расширение
 * в пропущенное событие. Обратное правило — у **запроса** квитанции, где
 * `additionalProperties: false`: направления совместимости противоположны.
 */
export function adaptUnreadChanged(event: unknown): UnreadChange | null {
  if (!isRecord(event) || event.type !== "unread.changed") return null

  const conversationId = event.conversation_id
  const unreadCount = event.unread_count

  // Пустая строка на месте идентификатора — выдуманное значение, а не
  // отсутствие: она не совпала бы ни с одной беседой списка и молча потеряла
  // бы событие под видом его применения.
  if (typeof conversationId !== "string" || conversationId.length === 0) return null

  // Отрицательное и дробное число — не счётчик. Ноль законен: он говорит
  // «непрочитанного нет», и это настоящее утверждение, а не отсутствие.
  if (typeof unreadCount !== "number" || !Number.isInteger(unreadCount) || unreadCount < 0) {
    return null
  }

  return { conversationId, unreadCount }
}

/**
 * Список бесед с наложенным оверлеем — новым массивом, а не правкой на месте.
 *
 * Беседа оверлея, которой нет в списке, пропускается: показать её нечем, а
 * завести беседу из одного числа значило бы выдумать содержимое. Это не потеря
 * факта — список придёт со следующей сверкой, и число в нём будет то же.
 *
 * Список бесед без записи в оверлее остаётся как есть — вместе с **отсутствием**
 * `unreadCount`, если его не было: «сервер не сказал» и «всё прочитано» —
 * разные состояния, и оверлей не имеет права делать их одним.
 */
export function withUnreadOverlay(
  conversations: readonly Conversation[],
  overlay: ReadonlyMap<string, number>,
): Conversation[] {
  if (overlay.size === 0) return conversations as Conversation[]

  return conversations.map((conversation) => {
    const unreadCount = overlay.get(conversation.id)
    return unreadCount === undefined ? conversation : { ...conversation, unreadCount }
  })
}
