/**
 * Конфигурация, которая не может лежать в бандле.
 *
 * Один и тот же образ статики обязан обслуживать окружения с разными именами
 * источника идентичности — в этом и состоит `DEP-001`: «собрано один раз,
 * продвинуто без пересборки». Пока имя вшито в бандл, второго окружения без
 * второй сборки не бывает, а бандл собирается из кода — то есть из коммита, а
 * не из окружения. Поэтому окружение приносит его с собой: файл рядом с
 * `index.html`, подключённый до модуля приложения, а не внутри него.
 *
 * Поле здесь **одно**, и это не заготовка под будущий «общий конфиг
 * приложения»: адрес API относителен и от окружения не зависит, адрес
 * Centrifugo, телеметрия, признаки функций и имя окружения в G3-005 наружу не
 * выходят вовсе. Второе поле появится вместе с той возможностью, которой оно
 * служит, — а не заранее, чтобы «конфигурация была».
 *
 * Значения по умолчанию нет намеренно: незаполненное поле дало бы сборку,
 * которая тихо ходит не туда, куда её настроили, и расхождение нашлось бы
 * глазами человека, увидевшего чужой экран входа. Отсутствие конфигурации —
 * это отказ развёртывания, и он обязан быть громким.
 */

/** Что окружение сообщает браузеру. */
export interface RuntimeConfig {
  /** Источник идентичности стенда: `https://<хост>/realms/<реалм>`. */
  readonly oidcIssuer: string;
}

declare global {
  interface Window {
    /**
     * Заводится файлом `/runtime/runtime-config.js`, который приходит из ConfigMap
     * окружения (том в чарте), а не из образа. `unknown`, а не `RuntimeConfig`:
     * содержимое файла нашему контролю не подчинено, и объявить его типом
     * значило бы утверждать о нём то, чего мы не проверяли.
     */
    __MESSENGER_RUNTIME_CONFIG__?: unknown;
  }
}

/**
 * Конфигурации нет или она неполна.
 *
 * Отдельный тип, а не `Error` с текстом: этот отказ наступает до всякого
 * взаимодействия с сервером, и вызывающий обязан отличать его от сетевого —
 * повтор кнопкой здесь не помогает, потому что чинить надо развёртывание.
 */
export class RuntimeConfigMissingError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "RuntimeConfigMissingError";
  }
}

/**
 * Читает конфигурацию окружения.
 *
 * Читается в момент, когда значение понадобилось, а не при загрузке модуля:
 * отказ тогда называет то, что человек делал (нажал «Войти»), а не «страница
 * не открылась» — и это разные вопросы при разборе.
 */
export function loadRuntimeConfig(): RuntimeConfig {
  const raw: unknown = window.__MESSENGER_RUNTIME_CONFIG__;
  if (typeof raw !== "object" || raw === null) {
    throw new RuntimeConfigMissingError(
      "Конфигурация окружения не загружена: файл /runtime/runtime-config.js не подключён или не отдан",
    );
  }

  const { oidcIssuer } = raw as Partial<RuntimeConfig>;
  if (typeof oidcIssuer !== "string" || oidcIssuer === "") {
    throw new RuntimeConfigMissingError(
      "В конфигурации окружения нет oidcIssuer: разворачивать не с чем, источника идентичности у сборки нет",
    );
  }

  return { oidcIssuer };
}
