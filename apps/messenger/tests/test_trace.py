"""Контекст трассировки: разбор заголовка, привязка, проход через границу.

Проверяется ровно то, ради чего `trace_id` вообще заведён: одна и та же
трасса видна в записи API, в записи отправителя и в записи потребителя.
Если это ломается, журнал всё ещё выглядит исправным — и это худший
вид поломки в наблюдаемости, потому что заметен он только на разборе
инцидента, когда искать уже поздно.
"""
from __future__ import annotations

from messenger.telemetry import trace
from messenger.telemetry.logging import SPAN_ID, TRACE_ID

ТРАССА = "4bf92f3577b34da6a3ce929d0e0e4736"
УЧАСТОК = "00f067aa0ba902b7"


def test_заголовок_разбирается():
    assert trace.parse(f"00-{ТРАССА}-{УЧАСТОК}-01") == (ТРАССА, УЧАСТОК)


def test_заголовок_с_флагом_выборки_ноль_всё_равно_разбирается():
    # `00` означает «не выбрано для экспорта», а не «контекста нет».
    # Отбросив такой заголовок, мы разорвали бы цепочку ровно там, где
    # чужой сервис решил не экспортировать свою половину.
    assert trace.parse(f"00-{ТРАССА}-{УЧАСТОК}-00") == (ТРАССА, УЧАСТОК)


def test_негодный_заголовок_не_ошибка_а_отсутствие_контекста():
    for негодный in (
        None,
        "",
        "мусор",
        f"01-{ТРАССА}-{УЧАСТОК}-01",          # чужая версия
        f"00-{ТРАССА}-{УЧАСТОК[:8]}-01",      # короткий участок
        f"00-{'0' * 32}-{УЧАСТОК}-01",        # нулевая трасса
        f"00-{ТРАССА}-{'0' * 16}-01",         # нулевой участок
        f"00-{'z' * 32}-{УЧАСТОК}-01",        # не шестнадцатеричное
    ):
        assert trace.parse(негодный) is None, негодный


def test_привязка_ставит_и_снимает_контекст():
    assert TRACE_ID.get() is None
    with trace.bind(trace_id=ТРАССА) as текущая:
        assert текущая == ТРАССА
        assert TRACE_ID.get() == ТРАССА
        assert SPAN_ID.get() is not None
    # Снятие важнее установки: процесс потребителя обрабатывает события
    # подряд, и оставшийся contextvar приписал бы чужую трассу следующему.
    assert TRACE_ID.get() is None
    assert SPAN_ID.get() is None


def test_вложенная_привязка_возвращает_внешнюю():
    with trace.bind(trace_id=ТРАССА):
        with trace.bind(trace_id="a" * 32):
            assert TRACE_ID.get() == "a" * 32
        assert TRACE_ID.get() == ТРАССА


def test_привязка_без_трассы_заводит_свою():
    with trace.bind() as текущая:
        assert len(текущая) == 32
        assert trace.parse(trace.header_for(текущая, trace.new_span_id())) is not None


def test_трасса_берётся_из_заголовка_записи():
    headers = {trace.HEADER: f"00-{ТРАССА}-{УЧАСТОК}-01"}
    assert trace.from_carrier(headers, {"trace_id": "b" * 32}) == ТРАССА


def test_тело_запасной_путь_для_записи_без_заголовка():
    # Событие, записанное отправителем прежней версии, заголовка не имеет,
    # но `trace_id` в теле у него есть — контракты его допускают с самого
    # начала. Терять на этом трассу незачем.
    assert trace.from_carrier({}, {"trace_id": ТРАССА}) == ТРАССА


def test_без_обоих_источников_трассы_нет():
    assert trace.from_carrier({}, {}) is None
    assert trace.from_carrier({}, {"trace_id": ""}) is None
    assert trace.from_carrier({}, {"trace_id": 42}) is None
