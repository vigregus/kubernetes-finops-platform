"""Непрочитанное: что считается непрочитанным и что делать с номером.

Проекция непрочитанного — **производная**, а не счётчик, который надо
поддерживать. Источник истины — `messages` и `read_states`, и модуль держит
ту половину правил, которую можно решить, не глядя в базу: как выглядит
событие `message.created`, какое сообщение непрочитано у читателя и в каком
случае номер события не продолжает чекпойнт.

Отсюда форма: предикат существует в одном экземпляре на Python здесь и в
одном экземпляре на SQL в `repositories/unread.py`
(`UNREAD_PREDICATE`). Разойтись они могут, поэтому тождество не
постулируется: интеграционная сверка `reconciliation` доводит проекцию
событиями, затем пересобирает её из источника истины и сравнивает числа
поимённо по каждому участнику.

**Идемпотентность держится порядком, а не журналом.** Событие несёт
`event_id`, но повтор отсекается не им: `message.created` партиционируется
по `conversation_id`, поэтому порядок внутри беседы сохраняется, и
достаточно монотонного `applied_through_seq` на беседу. `event_id`
остаётся идентификатором события и корреляцией.

**Чекпойнт — один на беседу, а не на пару (пользователь, беседа).**
Различие не косметическое, и видно на последовательности 10 (B→A),
11 (A→B), 12 (B→A). Чекпойнт пользователя A, сдвигаемый только по чужим
сообщениям, остановился бы на 10; увидев 12, он счёл бы 11 потерянным —
хотя 11 собственное сообщение A и непрочитанное не увеличивает, — и
уехал бы в пересборку на ровном месте. Поэтому чекпойнт двигается **любым**
`message.created`, а признак «чужое» применяется только к приращению.
"""
from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from enum import StrEnum
from typing import Any, NewType
from uuid import UUID

from messenger.domain.history import MAX_SEQ
from messenger.domain.ids import ConversationId, ConversationSeq, EventId, UserId

# Тип события, которое несёт номер в беседе. Других таких нет: чекпойнт
# определён как «наибольший применённый conversation_seq», а его несёт
# только факт появления сообщения.
EVENT_TYPE = "message.created"

# Счётчик непрочитанного. Отдельный тип от `ConversationSeq` не ради
# педантичности: перепутать их в вызове — значит записать номер туда,
# где ждут число, и это ошибка, которую видно не сразу.
UnreadCount = NewType("UnreadCount", int)

# «Не применено ничего» и «непрочитанного нет». Оба нули, и оба законны:
# строка чекпойнта заводится нулём при первом обращении, а у беседы без
# сообщений счётчик равен нулю по определению.
NO_SEQ = ConversationSeq(0)
NO_UNREAD = UnreadCount(0)

# Предел номера: тот же, что у квитанции, и по той же причине. `asyncpg`
# отдаст `DataError` на приведении к `bigint`, то есть вместо ожидаемого
# отказа получится сбой обработчика на ровном месте.
MAX_UNREAD_SEQ = ConversationSeq(MAX_SEQ)


class InvalidEvent(ValueError):
    """Событие, разобрать которое нельзя. Ожидаемый отказ, а не сбой.

    Код отделён от текста намеренно: текст уходит в журнал человеку, код —
    в поле `result`-записи, и по нему ищут. Смешать их значило бы искать
    по строкам, которые меняются при каждой правке формулировки.

    Исключение, а не значение, по образцу `InvalidReceipt`: вызывающий
    обязан обработать отказ явно, а `return None` на месте события
    разошёлся бы по всем местам, где событие ожидается непустым.
    """

    def __init__(self, code: str, detail: str) -> None:
        super().__init__(f"{code}: {detail}")
        self.code = code


@dataclass(frozen=True, slots=True)
class MessageCreated:
    """Факт появления сообщения — то, что нужно счётчику.

    Содержимого здесь нет и быть не может: в потоке факта его нет
    (`SEC-010`), а потребителю непрочитанного текста не нужно.

    `recipient_ids` — состав беседы **на момент отправки** (так его
    описывает контракт). `None` означает, что состав не пришёл: схема
    объявляет поле необязательным, и трактовать его отсутствие как отказ
    нельзя — событие не негодное, оно просто менее полное. Разбирается
    это вызывающим: он уходит в пересборку из источника истины, то есть
    ровно туда, где состав берётся из `conversation_members`.
    """

    event_id: EventId
    conversation_id: ConversationId
    conversation_seq: ConversationSeq
    sender_id: UserId
    recipient_ids: tuple[UserId, ...] | None = None


class UnreadOutcomeKind(StrEnum):
    """Исход применения одного события. Разные исходы — разные записи в журнале.

    `REBUILT` — единственная форма восстановления, и она же ответ на три
    разных повода: разрыв номеров, отсутствующий состав в событии и
    пропавшая строка проекции. Свести их в один исход — не упрощение
    ради краткости: во всех трёх случаях число берётся из источника
    истины целиком, а не приращением, и различать их в коде значило бы
    завести три ветки с одинаковым телом. Различает их `reason`: три
    разных происшествия с одной реакцией — это то, что оператор обязан
    видеть врозь, но чинить одинаково.
    """

    APPLIED = "applied"
    DUPLICATE = "duplicate"
    REBUILT = "rebuilt"
    IGNORED = "ignored"
    INVALID = "invalid"


@dataclass(frozen=True, slots=True)
class UnreadOutcome:
    """Что вышло из одного события.

    `affected` — сколько строк проекции записано, то есть изменено или
    создано. Не «сколько пользователей затронуто»: отправитель входит
    в затронутые, но его строка остаётся прежней, и в число он не
    попадает. И не «сколько прибавлено»: пересборка пишет абсолютные
    значения, и участник с нулём непрочитанного в неё входит.

    Различие нужно журналу и тестам. `affected = 0` у приращения
    означает беседу без собеседников (или одного отправителя), а у
    пересборки его быть не может: она возвращает строку на каждого
    действующего участника.
    """

    kind: UnreadOutcomeKind
    conversation_id: ConversationId | None = None
    conversation_seq: ConversationSeq | None = None
    affected: int = 0
    # Короткий код, а не текст: он уходит в поле записи журнала и по нему
    # ищут. Заполнен у `REBUILT` (что именно заставило пересобрать)
    # и у `INVALID` (что было не так с событием); у остальных исходов
    # причины нет — она и есть сам исход.
    reason: str | None = None


@dataclass(frozen=True, slots=True)
class UnreadDelta:
    """Приращение счётчика одного пользователя.

    Объект, а не пара: два идентификатора подряд в вызове однажды
    меняются местами, а `UnreadDelta` распаковать по позиции нечем.
    """

    user_id: UserId
    delta: UnreadCount


def event_type_of(body: Mapping[str, Any]) -> str:
    """Тип события из тела; пустая строка — типа нет.

    Не исключение: тип нужен отбору и журналу, а не разбору. Событие
    чужого типа — не негодное, а постороннее, и исход у него другой.
    """
    value = body.get("event_type")
    return value if isinstance(value, str) else ""


def parse_message_created(body: Mapping[str, Any]) -> MessageCreated:
    """Тело события → `MessageCreated`. Отказ — `InvalidEvent`.

    Тип события здесь **не** проверяется: его проверяет вызывающий, и это
    не оплошность. Постороннее событие и событие негодное — разные исходы
    (пропустить молча против записать отказ), а одна проверка на два
    исхода заставила бы разбирать текст исключения.

    Разбор строгий там, где ошибка иначе прошла бы молча. `bool` — подкласс
    `int`, и без отдельной ветки `"conversation_seq": true` стал бы номером
    `1`, то есть событием, которого не было. Номер ниже единицы отвергается,
    потому что контракт объявляет `minimum: 1`, а чекпойнт начинается с нуля:
    пропусти такой номер дальше, и он лёг бы в чекпойнт как «применённое
    событие», которого не существует.
    """
    event_id = _uuid(body, "event_id")
    conversation_id = _uuid(body, "conversation_id")
    sender_id = _uuid(body, "sender_id")
    sequence = _seq(body, "conversation_seq")
    if sequence < 1:
        raise InvalidEvent(
            "bad_seq",
            f"conversation_seq ({sequence}) меньше 1: события с таким номером не бывает",
        )
    if sequence > MAX_UNREAD_SEQ:
        raise InvalidEvent(
            "bad_seq",
            f"conversation_seq ({sequence}) больше предела int64 ({MAX_UNREAD_SEQ})",
        )
    return MessageCreated(
        event_id=EventId(event_id),
        conversation_id=ConversationId(conversation_id),
        conversation_seq=ConversationSeq(sequence),
        sender_id=UserId(sender_id),
        recipient_ids=_recipients(body),
    )


def is_foreign(sender_id: UserId | None, *, reader_id: UserId) -> bool:
    """Чужое ли сообщение для читателя. `None` (стёртый автор) — чужое.

    Отдельная функция ради того, чтобы совпадение с `IS DISTINCT FROM`
    было видно, а не подразумевалось. В Python `None != reader_id` уже
    истинно, и наивная запись `sender_id != reader_id` дала бы то же
    самое — но ровно до первой правки, где сравнение перепишут на
    `==` с инвертированным условием и потеряют стёртого автора.
    В SQL это не стилистика: `<>` с `NULL` даёт `NULL`, то есть строка
    не попадает **ни** в свои, **ни** в чужие, и счётчик собеседника
    молча уменьшается.
    """
    return sender_id is None or sender_id != reader_id


def counts_as_unread(
    *,
    sender_id: UserId | None,
    reader_id: UserId,
    conversation_seq: ConversationSeq,
    last_read_seq: ConversationSeq,
    applied_through_seq: ConversationSeq,
) -> bool:
    """Единственный предикат непрочитанного — три члена и ни одного лишнего.

    Соответствует SQL-половине (`_unread_predicate` в репозитории) член
    в член, и проверяется это сверкой `reconciliation`, а не глазами.

    **Надгробие считается, и это следует из того, что здесь считается.**
    Предикат считает чужие **позиции** `conversation_seq` выше
    `last_read_seq`, а не сообщения с доступным содержимым. Удаление
    содержимого не уменьшает счётчик само по себе: читатель эту позицию
    ещё не наблюдал, а при чтении увидит на её месте надгробие — то есть
    пропущенное им место в беседе, а не пустоту. Поэтому `deleted_at`
    в предикате не участвует.

    Техническая сторона того же решения не менее важна: потребитель идёт
    по `message.created`, события удаления в потоке нет вовсе, поэтому
    исключение надгробий из пересчёта сделало бы пересборку строго меньше
    приращения — и разошлось бы с ним не иногда, а всегда. Пути удаления
    сообщения в v1 не существует (операция не заведена — ни маршрута,
    ни сервиса), поэтому «коррекции при удалении» было бы негде
    вызываться, а расхождение чинить нечем. Порядок в беседе цел
    (`DATA-004`, `CLI-001`).

    Если продукт потребует, чтобы удаление непрочитанного **немедленно**
    уменьшало счётчик, это будет новое решение и новая работа: пересчёт
    проекции под замком беседы вешается на операцию удаления — так же,
    как он висит на квитанции, — а предикат получает `deleted_at IS NULL`
    в одном месте, в `_unread_predicate`.

    **Верхняя граница — не формальность.** Сообщение с номером выше
    чекпойнта уже лежит в Postgres, но потребителем ещё не применено,
    и в счёт попадать не должно: иначе квитанция, пришедшая вперёд
    потребителя, обнулила бы счётчик, а потребитель нагнал бы его
    повторным приращением по устаревшему `last_read_seq`.

    В обычном шаге (событие продолжает чекпойнт) верхняя граница равна
    самому номеру и проверка вырождается — но остаётся здесь, чтобы
    предикат был один, а не один с оговоркой.
    """
    return (
        conversation_seq > last_read_seq
        and conversation_seq <= applied_through_seq
        and is_foreign(sender_id, reader_id=reader_id)
    )


def affected_users(
    *, recipients: Sequence[UserId], sender_id: UserId
) -> tuple[UserId, ...]:
    """Кого касается событие: получатели на момент отправки и отправитель.

    Отправитель входит не ради симметрии. Строка проекции нужна каждому
    участнику беседы: список бесед читает счётчики пользователя, и у
    отправителя счётчик тоже есть — ноль. Не будь его строки, собственные
    беседы показывали бы «неизвестно» до первой квитанции, то есть
    **всегда** для того, кто только пишет и не читает. Приращение для
    отправителя при этом ноль, и получается это само: `counts_as_unread`
    для собственного сообщения ложна.

    Повтор в составе не предполагается контрактом, но и не запрещён;
    `dict.fromkeys` убирает его, сохраняя порядок, — иначе на одного
    пользователя пришлось бы две строки в одной вставке, а `ON CONFLICT`
    в пределах одного оператора такого не переживает.
    """
    return tuple(dict.fromkeys((*recipients, sender_id)))


def _uuid(body: Mapping[str, Any], name: str) -> UUID:
    value = body.get(name)
    if not isinstance(value, str):
        raise InvalidEvent("missing_field", f"поле {name} отсутствует или не строка")
    try:
        return UUID(value)
    except ValueError as exc:
        raise InvalidEvent("bad_uuid", f"поле {name} не идентификатор: {value}") from exc


def _seq(body: Mapping[str, Any], name: str) -> int:
    value = body.get(name)
    # `bool` проверяется отдельно: он подкласс `int`, и `true` прошёл бы
    # как единица. Тот же случай, что в валидаторе квитанции.
    if isinstance(value, bool) or not isinstance(value, int):
        raise InvalidEvent("missing_field", f"поле {name} отсутствует или не целое")
    return value


def _recipients(body: Mapping[str, Any]) -> tuple[UserId, ...] | None:
    """Состав из события; `None` — состава нет.

    Отсутствие поля и пустой список различимы и означают разное. Пустой
    список — «получателей не было»: у беседы, из которой все вышли, это
    законный ответ, и пересборка ему ничего не добавит. Отсутствие поля —
    «состав неизвестен», и это единственный случай, когда вызывающему
    есть смысл идти в `conversation_members`.
    """
    value = body.get("recipient_ids")
    if value is None:
        return None
    if not isinstance(value, list):
        raise InvalidEvent("bad_recipients", "recipient_ids не список")
    return tuple(UserId(_uuid({"user_id": item}, "user_id")) for item in value)
