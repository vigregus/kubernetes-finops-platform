"""Присутствие: когда человек считается в сети и когда он был в сети.

Два разных вопроса, и различие между ними — не оттенок, а причина, по
которой модуль существует.

**«Онлайн» — предикат о времени, а не событие.** У Centrifugo нет прокси
на отключение: проксируются `connect`, `refresh`, `subscribe`, `publish`,
`sub_refresh`, `rpc`, а о разрыве сервер не узнаёт никогда — ни при
закрытии вкладки, ни при потере сети, ни при убитом процессе. Поэтому
единственный признак жизни — продление: `connect` выдаёт
`expire_at = now + token_ttl_seconds`, Centrifugo продлевает соединение
периодическими вызовами refresh-proxy, а ушедший клиент продлевать
перестаёт. Отсюда правило: соединение живо, пока `refreshed_at` попадает
в окно, и статус пользователя — **проекция времени**, которую можно
посчитать в любой момент, а не состояние, которое кто-то обязан
переключить.

**«Был в сети» — факт, и он не выводится из «онлайн».** Отметка пишется
в Postgres при подтверждении жизни и монотонна (`repositories/users.py`).
Вычислять её как «момент, когда уборщик заметил уход» нельзя: уборщик
отстаёт на свой период, а при мёртвом уборщике не наступает вовсе — и
человек выглядел бы бывшим в сети позже, чем был. Поэтому отметка ставится
при подтверждении, а не при потере, и переживает и перезапуск Centrifugo,
и смерть уборщика.

**Статус — агрегат по пользователю, а не по соединению.** Одна сессия
живёт во стольких вкладках, сколько их открыто, и в двух устройствах.
Считать статус по соединению значило бы показывать «ушёл» на закрытии
одной вкладки из двух — та самая ошибка, ради которой правило вынесено
в требования (`PRS-001`). Собственные presence/join_leave Centrifugo её
не закрывают: они привязаны к подписке, то есть к соединению.

Предикат живёт здесь на Python и в `repositories/sessions.py` на SQL.
Разойтись они могут, поэтому тождество не постулируется: правило
агрегации проверяется интеграционно (`tests/integration/presence_check.py`)
на двух устройствах одного пользователя — протухшем и свежем.
"""
from __future__ import annotations

from datetime import datetime, timedelta

# Окно живости соединения.
#
# Обязано быть **больше** каденции продления (`token_ttl_seconds`, 120 с):
# Centrifugo продлевает соединение примерно раз в неё, и окно короче
# означало бы, что живой клиент мигает офлайн между продлениями — то есть
# отказ, который выглядит как флапающая сеть, а не как неверная константа.
# 180 с при 120 с дают запас на один пропущенный такт: одиночная заминка
# продления (сборка мусора, пауза сети в один круг) статус не меняет.
#
# Тождество «окно > каденции» не постулируется, а проверяется юнит-тестом
# (`apps/messenger/tests/test_presence.py`): два числа в разных модулях
# разошлись бы молча.
ONLINE_WINDOW_SECONDS = 180


def online_cutoff(now: datetime) -> datetime:
    """Левая граница окна: соединение с `refreshed_at` не старше неё живо.

    Считается от переданного `now`, а не от часов внутри: у вызывающего
    (SQL-половина правила) свой источник времени, и второй здесь означал бы
    две границы вместо одной.
    """
    return now - timedelta(seconds=ONLINE_WINDOW_SECONDS)


def is_online(refreshed_at: datetime | None, *, now: datetime) -> bool:
    """Живо ли соединение. `None` — соединения нет, и это не «живо».

    Граница включающая: `refreshed_at == cutoff` ещё живо. Направление
    выбрано так, чтобы окно было ровно объявленной длины, а не на мгновение
    короче.
    """
    return refreshed_at is not None and refreshed_at >= online_cutoff(now)


def last_seen_of(current: datetime | None, confirmed: datetime) -> datetime:
    """Новая отметка «был в сети»: наибольшая из прежней и подтверждённой.

    Соответствует `GREATEST(last_seen_at, now())` в SQL, и это не
    украшение. Два устройства одного человека продлеваются независимо,
    и при присваивании проигравшая гонка записала бы более старое время:
    отметка поехала бы назад. Монотонность здесь — то же требование, что
    у `updated_at` снимка, и по той же причине: назад время не идёт.

    `None` (ни разу не был в сети) — не особый случай: максимум из
    «неизвестно» и подтверждённого есть подтверждённое. В SQL это
    получается само — `GREATEST` игнорирует `NULL`, — и ветка здесь
    повторяет то же поведение, а не добавляет своё.
    """
    if current is None:
        return confirmed
    return max(current, confirmed)


def online_share(*, online: int, registered: int) -> float:
    """Доля пользователей в сети. Ноль знаменателя — ноль доли.

    Знаменатель — заведённые учётные записи без надгробий. Доля нужна
    метрике (`messenger_presence_online_share`), и делить на ноль в ней
    нельзя: на пустой базе деление уронило бы такт уборщика, то есть
    отказ ровно там, где смотреть не на что.
    """
    if registered <= 0:
        return 0.0
    return online / registered
