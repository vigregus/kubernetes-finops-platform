"""Пользователь: сущность и правила, не знающие ни о базе, ни о Keycloak.

Пароли, вход и вторая ступень живут в Keycloak; здесь — профиль и связи.
Поэтому ключ, по которому пользователь узнаётся, — `external_id` из токена,
а не адрес почты: адрес меняется, и привязка к нему однажды разъедет учётную
запись с её историей.

Три правила вынесены сюда из репозитория намеренно. Нормализация адреса,
обрезка отображаемого имени и признак «удалён» — доменные решения, и они
обязаны быть одинаковыми независимо от того, кто вызвал: обработчик HTTP,
потребитель Kafka или административная команда.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from enum import Enum

from messenger.domain.ids import UserId

# Длина отображаемого имени. Ограничение не косметическое: имя уходит
# в список бесед и в push-уведомление, а строка на десять тысяч символов
# ломает и то, и другое.
DISPLAY_NAME_MAX = 64

# Запасное имя. Пустое имя в интерфейсе выглядит как ошибка загрузки,
# а не как отсутствие имени, и первым делом идут в поддержку.
FALLBACK_DISPLAY_NAME = "Без имени"


@dataclass(frozen=True, slots=True)
class User:
    """Профиль. Неизменяемый: обновление — это новая запись из базы.

    Изменяемый объект, живущий дольше запроса, однажды окажется в кеше
    и начнёт отдавать состояние, которого в базе уже нет.
    """

    user_id: UserId
    external_id: str
    display_name: str
    email: str | None
    email_verified: bool
    created_at: datetime
    updated_at: datetime
    deleted_at: datetime | None = None

    @property
    def is_deleted(self) -> bool:
        """Надгробие, а не отсутствие строки.

        На пользователя ссылаются сообщения, и физическое удаление
        обрушило бы историю чужих бесед. Проверять приходится явно:
        «строка нашлась» больше не означает «человек здесь».
        """
        return self.deleted_at is not None


@dataclass(frozen=True, slots=True)
class UserSummary:
    """Кто виден в списке бесед: имя типа взято из контракта, не выдумано.

    Не `User` и не его урезанная копия. Полный профиль тянет за собой
    `external_id` (ключ Keycloak, наружу отдавать нечего), `email` и
    `email_verified` — то есть почту и признак её подтверждения каждого
    участника каждой беседы в ответе на список. Список показывает имя
    и идентификатор, и это всё, что ему нужно.

    `display_name` объявлен `str`, а не `str | None`, и это **долг**, а не
    решение: `0002_erasure.sql` снял с `users.display_name` непустоту —
    у стёртого профиля остаётся скелет без содержимого, — а контракт
    (`UserSummary.display_name`) объявляет поле обязательным и не нулевым.
    Сегодня недостижимо: пути стирания в коде нет. Тот же класс, что
    `sender_id` у сообщения, и решать его надо тем же решением; записан
    в `IMPLEMENTATION-PLAN.md`. Живёт этот долг уже сейчас: `POST
    /conversations` отдаёт `display_name` участника с первого дня.
    """

    user_id: UserId
    display_name: str


def normalize_email(raw: str | None) -> str | None:
    """Приводит адрес к виду, по которому он сравнивается.

    Нижний регистр и обрезанные пробелы — потому что уникальность в базе
    держится частичным индексом по `lower(email)`. Нормализуй в одном месте
    и не нормализуй в другом — и `A@x.ru` заведёт вторую учётную запись
    рядом с `a@x.ru`, а владелец обеих не поймёт, куда делась переписка.

    Пустая строка — это отсутствие адреса, а не адрес: Keycloak присылает
    `""` для учётной записи без почты, и такой «адрес» попал бы в индекс.
    """
    if raw is None:
        return None
    value = raw.strip().lower()
    return value or None


def normalize_display_name(raw: str | None) -> str:
    """Обрезает имя до допустимой длины и подставляет запасное.

    Обрезка здесь, а не в базе: `varchar(64)` отклонил бы вставку целиком,
    то есть вход был бы невозможен из-за длинного имени в чужом каталоге.
    """
    value = (raw or "").strip()
    if not value:
        return FALLBACK_DISPLAY_NAME
    return value[:DISPLAY_NAME_MAX]


@dataclass(frozen=True, slots=True)
class EnsureUserResult:
    """Результат приведения профиля к состоянию из токена.

    Объект, а не кортеж: `created` понадобится метрике регистраций, и
    добавление четвёртого поля не должно ломать вызывающих.
    """

    user: User
    # Учётная запись заведена этим вызовом. Второй вход того же человека
    # возвращает False — это и есть идемпотентность `ensure_*`.
    created: bool
    # Профиль отличался от токена и был обновлён.
    updated: bool = False


class Capability(str, Enum):
    """Что человек может делать. Проверяется до действия, а не после.

    Список короткий намеренно: это не система прав, а ответ на один
    вопрос — что доступно до подтверждения адреса (`AUTH-006`).
    """

    # Читать свои беседы и сообщения. Доступно всегда: запрет на чтение
    # своей же переписки выглядел бы как потеря данных.
    READ = "read"
    # Писать в существующую беседу.
    SEND_MESSAGE = "send_message"
    # Начинать беседу с кем-то новым.
    START_CONVERSATION = "start_conversation"


# Что доступно, пока адрес не подтверждён.
#
# Ограничение бьёт именно по рассылке незнакомым: учётная запись
# с чужим или выдуманным адресом заводится за секунду, и без этого
# ограничения она сразу же начинает писать посторонним. Чтение и ответ
# в уже существующей беседе при этом остаются — иначе человек, которого
# позвали первым, не может ответить, и ограничение бьёт по нему,
# а не по рассылающему.
_UNVERIFIED = frozenset({Capability.READ, Capability.SEND_MESSAGE})
_VERIFIED = frozenset(Capability)


def capabilities_of(user: User) -> frozenset[Capability]:
    """Возможности профиля. Одно место, а не условие в каждом обработчике.

    Разложенное по обработчикам правило однажды забудут в одном из них —
    и это будет ровно тот, через который рассылают.
    """
    if user.is_deleted:
        # Надгробие не может ничего. Строка в базе есть, человека нет.
        return frozenset()
    return _VERIFIED if user.email_verified else _UNVERIFIED


def can(user: User, capability: Capability) -> bool:
    return capability in capabilities_of(user)
