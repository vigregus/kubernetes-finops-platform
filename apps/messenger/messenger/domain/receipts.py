"""Квитанция: два номера одного состояния, их пределы и нормализация.

Квитанция — не сущность рядом с `Message`, а **отчёт клиента о своём
положении в беседе**: «до меня дошло до номера K, прочитано до номера M».
Хранится это одной строкой `read_states` на пару (беседа, пользователь), и
модуль держит ровно то, что можно решить, не глядя в базу: пределы чисел,
соотношение между ними и приведение отчёта к состоянию.

**Квитанция описывает состояние, а не событие.** Отсюда все три правила.
Монотонность: опоздавшая квитанция не откатывает счётчик — иначе пересказ
«дошло до 3», пришедший после «дошло до 7», объявил бы потерянными четыре
дошедших сообщения. Чтение подразумевает получение: прочитать неполученное
нельзя, поэтому доставленное поднимается до прочитанного, а не наоборот.
И оба числа не могут превышать голову беседы: `last_seq = k` наблюдаемо ровно
тогда, когда наблюдаемо сообщение `k`, поэтому номер выше головы не мог прийти
ни потоком, ни прошлым ответом.

**Здесь только правила, а не их исполнение.** Монотонность обеспечивает SQL
(`GREATEST` против хранимой строки), потому что она обязана держаться под
гонкой двух устройств, а не в промежутке между чтением и записью. Модуль
готовит пару, из которой `delivered >= read` следует по построению, — и
именно поэтому дальше безопасны `NOT NULL` на обеих колонках и `CHECK`,
оставленный миграцией `0009` проверенным.
"""
from __future__ import annotations

from dataclasses import dataclass

from messenger.domain.history import MAX_SEQ
from messenger.domain.ids import ConversationSeq

# Нижняя граница — из контракта (`minimum: 0`), а не из удобства. Ноль
# означает «ещё ничего» и законен: беседа создана, сообщений нет, и свежая
# строка `read_states` состоит из двух нулей.
MIN_RECEIPT_SEQ = 0


class InvalidReceipt(ValueError):
    """Негодный номер квитанции. Ошибка клиента, ответ — `400`.

    Отдельно от `InvalidCursor`, хотя соблазн переиспользовать велик: у
    `InvalidCursor` тот же смысл («ошибка клиента, видимая рядом с данными»)
    и тот же класс ответа. Но код ответа у них разный — `invalid_cursor`
    против `invalid_receipt`, — а `_invalid_cursors` в API собирает ответ
    для своего типа. Переиспользовать тип значило бы либо соврать в `code`,
    либо завести второй сборщик на тот же тип, то есть ровно те два разных
    `400` на одну ошибку клиента, от которых предостерегает соседний
    `_invalid_cursors`.

    Одним исключением на оба случая — и на негодное само по себе, и на
    негодное рядом с данными, — по тому же основанию, что у `InvalidCursor`:
    разделив их, пришлось бы завести вторую `Reason` (таксономия закрыта и
    описывает данные и право, а не строку запроса) либо нести текст
    нарушения вторым каналом рядом с `rejection`.
    """


@dataclass(frozen=True, slots=True)
class Receipts:
    """Присланное клиентом. `None` — «не сообщили», и это **не** ноль.

    Различие живёт только здесь, до нормализации, и оно не косметическое:
    контракт требует, чтобы квитанция называла хотя бы одно поле
    (`anyOf`), — иначе опечатка в имени поля выглядела бы валидным телом.
    В состояние отчёт не переезжает: `state_of` переводит отсутствие
    в ноль, и на области, ограниченной снизу нулём, «не сообщили» и
    «сообщили ноль» неразличимы ни в одной последующей записи.
    """

    delivered_seq: int | None = None
    read_seq: int | None = None


@dataclass(frozen=True, slots=True)
class ReadState:
    """Состояние после применения — то, что отдаётся клиенту.

    Не `Receipts`: у этого типа оба поля есть всегда и `delivered >= read`
    выполнено по построению. Ответ на отставшую квитанцию несёт **текущее**
    значение, а не присланное, и именно этим клиент отличает «применено»
    от «проигнорировано».
    """

    delivered_seq: ConversationSeq
    read_seq: ConversationSeq


def validate_receipts(receipts: Receipts) -> None:
    """Пределы, видимые по одной квитанции. Отказ — `InvalidReceipt`.

    Здесь только то, что не требует данных, — функция обязана отвечать без
    базы, потому что вызывается рано, до соединения. Ничего про голову
    беседы тут быть не может: это отдельная проверка, и её текст зависит
    от того, какое поле оказалось выше.

    Пустая квитанция отвергается, хотя транспорт её и не пропустил бы:
    сервис зовут не только из обработчика, и домен, доверяющий `anyOf`
    из спецификации, защищён ровно до первого скрипта.

    Верхняя граница — не полнота ради полноты. Python и FastAPI примут
    `2**63` молча, а расхождение вылезет в драйвере: `asyncpg` отдаёт
    `DataError` на приведении к `bigint`, то есть вместо объявленного
    контрактом `400` клиент получит `500`. Ошибка клиента обязана
    оставаться ошибкой клиента.
    """
    if receipts.delivered_seq is None and receipts.read_seq is None:
        raise InvalidReceipt(
            "квитанция не называет ни одного номера: "
            "нужен delivered_seq или read_seq"
        )
    for name, value in (
        ("delivered_seq", receipts.delivered_seq),
        ("read_seq", receipts.read_seq),
    ):
        if value is None:
            continue
        if value < MIN_RECEIPT_SEQ:
            raise InvalidReceipt(
                f"{name} не может быть меньше {MIN_RECEIPT_SEQ}: {value}"
            )
        if value > MAX_SEQ:
            raise InvalidReceipt(
                f"{name} ({value}) больше предела int64 ({MAX_SEQ}): "
                "такого номера не может быть ни у одного сообщения"
            )


def validate_receipt_bound(receipts: Receipts, *, head: int) -> None:
    """Квитанция против головы беседы: ни один номер не выше `head`.

    Проверка идёт по **присланным** числам, до нормализации, и порядок
    обязателен. Нормализация поднимает доставленное до прочитанного,
    поэтому квитанция `read_seq=100, head=15` после неё выглядела бы как
    `delivered_seq=100` — и клиент получил бы отказ про поле, которого не
    присылал.

    Голова здесь — предел выданного, а не «состояние, которое можно
    освежить»: номер выше неё не мог прийти ни потоком, ни прошлым ответом,
    значит это ошибка клиента, а не гонка, и отвергать её можно без риска
    отказать законному запросу. Молчаливое ограничение максимумом выглядело
    бы для клиента применённой квитанцией: он никогда не узнал бы, что
    прислал невозможное число.

    Отсюда же следует, что голову обязан читать писатель. На отставшей
    реплике `last_seq` меньше головы, и честная квитанция получила бы
    ложный отказ.
    """
    for name, value in (
        ("delivered_seq", receipts.delivered_seq),
        ("read_seq", receipts.read_seq),
    ):
        if value is not None and value > head:
            raise InvalidReceipt(
                f"{name} ({value}) выше головы беседы ({head}): "
                "такого сообщения ещё нет"
            )


def state_of(receipts: Receipts) -> ReadState:
    """Присланное → состояние: отсутствие в ноль, чтение поднимает доставку.

    Оба `None` проверены выше, но переводятся здесь явно, а не через
    `or`: ноль — законное число (`minimum: 0`), и `receipts.read_seq or 0`
    неотличимо от верного только потому, что для нуля обе ветви дают ноль.
    На `delivered_seq` та же запись уже ошибочна: `delivered_seq=0` с
    `read_seq=5` дало бы `max(0, 5) = 5` — верно, — но `if receipts.delivered_seq`
    в любом будущем месте выбросило бы ноль, а ноль здесь — всё содержимое
    свежей строки.

    `delivered = max(delivered, read)` — это `RCP-004`: прочитать
    неполученное невозможно. Соотношение получается **по построению**, а не
    проверкой после, и это не стилистика: именно на него опираются `NOT NULL`
    обеих колонок и `CHECK` из миграции `0009`, которому больше нечего
    ловить, кроме ошибки в этой строке.
    """
    delivered = 0 if receipts.delivered_seq is None else receipts.delivered_seq
    read = 0 if receipts.read_seq is None else receipts.read_seq
    return ReadState(
        delivered_seq=ConversationSeq(max(delivered, read)),
        read_seq=ConversationSeq(read),
    )
