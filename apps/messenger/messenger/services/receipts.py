"""Запись квитанции: право, голова беседы, состояние и пересчёт проекции.

**Только запись.** Квитанция не рассылается: ни строки в `outbox`, ни
топика Kafka, ни публикации в Centrifugo. Схемы события `receipt.*` не
существует, канала под него нет, и выдумать его здесь значило бы выпустить
в провод событие без владельца. Оповещение собеседника — отдельная задача,
и она не входит в этот гейт.

**Транзакция: почему её не было и почему она появилась.** До `G3-003`
обёртка была не нужна, и это следствие, а не упущение: одна строка, одна
запись, границы согласованности нет. Голова монотонна, проверка границы
односторонняя, а изменение состояния — один `INSERT … ON CONFLICT DO
UPDATE`, атомарный сам по себе. С `G3-003` у квитанции появляется вторая
запись — проекция непрочитанного — и **второй писатель той же строки**:
потребитель со своим приращением. Обёртка нужна не потому, что «записей
стало больше одной», а потому, что **абсолютная запись обязана быть
упорядочена относительно приращения**, и упорядочивает её строка
`unread_offsets`, взятая первой. Прежнее правило «транзакция там, где
требуется атомарность нескольких шагов» не отменяется — им же этот случай
и покрывается: шагов стало два, и они пишут в две таблицы.

Прежнее замечание про `READ COMMITTED` остаётся в силе и **становится
доводом за блокировку**: открыть транзакцию мало, на `READ COMMITTED`
каждый оператор видит свой снимок, поэтому согласованность даёт не
обёртка, а замок беседы.

**Пересчёт — не «минус единица».** Квитанция может перескочить через
несколько сообщений сразу — `read_seq` приходит от устройства, и устройство
вправе прочитать всю беседу разом, — поэтому число берётся из источника
истины: `COUNT` по диапазону `(last_read_seq, applied_through_seq]`.
Верхняя граница — чекпойнт потребителя, а не голова беседы, и это тоже
решение: сообщение, уже лежащее в Postgres, но потребителем ещё не
применённое, в счёт не входит. Иначе квитанция обнулила бы счётчик, а
потребитель, догнав, прибавил бы единицу по устаревшему `last_read_seq`.

**Гонка, ради которой появился замок.** `applied_through_seq = 5`;
квитанция считает `COUNT((4, 5]) = 1` и собирается записать абсолютную
единицу. В этот момент потребитель применяет событие 6 и коммитит
приращение. Квитанция записывает своё `1` — вклад события 6 потерян, и
потерян навсегда: пересчитать его заново некому, потому что потребитель
идёт вперёд, а не назад. Без замка вторая нить зависла бы на строке
проекции, а строки может и не быть — блокировать нечего. Строка
`unread_offsets` существует всегда, и это второй довод за неё.

**Чего замок не делает.** Голова беседы читается **до** него, и это не
недосмотр. Голова — односторонняя граница (`≤ head`) для проверки
присланного, а не вход пересчёта: пересчёт ограничен чекпойнтом. Проверка
же опирается на то, что номер `k` клиент узнаёт только из коммита,
сделавшего `k` наблюдаемым, и узнаёт **до** того, как отправит квитанцию, —
значит любое чтение внутри обработки запроса видит не меньше `k`, и
устаревшую голову предъявить неоткуда. Читать её после замка значило бы
удерживать замок беседы на лишнем запросе — и держать его на беседе,
которой может уже не быть.

**Беседы исчезают, и это не гипотеза.** Прежняя редакция считала случай
`head is None` недостижимым — «беседы ничто не удаляет» — и держалась
за это дважды: здесь и в докстринге `lock_offsets`. Живой прогон это
опроверг: беседу удаляет уборка интеграционной проверки, и удаляет
вместе с производными (каскад `0011`), а не вместе с событиями о ней.
Отсюда обе ветки отказа — до замка и после него. Первая отвечает `404`
без транзакции, вторая тем же `404` из-под замка: чекпойнта у удалённой
беседы не остаётся, поэтому пустой ответ `lock_offsets` значит «беседы
нет», а не «замок не взялся». Различие это не косметическое — на нём
стоит вечный цикл потребителя, разобранный в `repositories/unread.py`.
"""
from __future__ import annotations

from dataclasses import dataclass

import asyncpg

from messenger.domain.authorization import Action, ResourceRef, Subject
from messenger.domain.errors import Reason, Visibility
from messenger.domain.ids import ConversationId
from messenger.domain.receipts import (
    ReadState,
    Receipts,
    state_of,
    validate_receipt_bound,
    validate_receipts,
)
from messenger.domain.unread import UnreadCount
from messenger.domain.user import User
from messenger.repositories import conversations, read_states
from messenger.repositories.unread import lock_offsets, recount_unread
from messenger.services import authorization


@dataclass(frozen=True, slots=True)
class SetReceiptsResult:
    """Состояние после применения либо отказ. Никогда то и другое сразу.

    `visibility` несут отказы авторизации: сервис знает, пришёл субъект по
    своей ссылке или подобрал идентификатор, и выбрасывать это знание здесь
    значило бы потерять его навсегда.

    `unread_count` — число после пересчёта. В тело ответа маршрута оно
    **не** попадает: контракт `POST /conversations/{id}/receipts` в этом
    гейте не расширяется, а `CTR-002` обязан остаться зелёным. Поле нужно
    вызывающему внутри процесса и тестам, которые им же и проверяют, что
    пересчёт идёт от источника истины, а не вычитанием единицы.
    """

    state: ReadState | None = None
    rejection: Reason | None = None
    visibility: Visibility = Visibility.HIDDEN
    unread_count: UnreadCount | None = None

    @property
    def ok(self) -> bool:
        return self.state is not None and self.rejection is None


async def set_receipts(
    conn: asyncpg.Connection,
    *,
    viewer: User,
    conversation_id: ConversationId,
    receipts: Receipts,
) -> SetReceiptsResult:
    """Применяет квитанцию и возвращает состояние, а не присланное.

    Ответ на отставшую квитанцию несёт **текущее** значение: этим клиент
    и отличает «применено» от «проигнорировано». Присланное возвращать
    нельзя — клиент счёл бы применённым то, что отвергнуто монотонностью.

    Порядок шагов не переставляется. Проверка пределов идёт первой, потому
    что негодная квитанция не должна занимать соединение с базой. Право
    проверяется **до** чтения головы: неучастник не должен получить
    прочитанную за него голову беседы, и первым он обязан получить отказ,
    а не отказ после работы. Граница — до нормализации, иначе квитанция
    `read_seq` выше головы была бы отвергнута под именем `delivered_seq`.

    Право спрашивается на **чтение** беседы, а не на запись. Квитанция
    подтверждает читаемое состояние, а беседу она не меняет, и в записанной
    модели доступа (`docs/messenger/08-authorization.md`) это разные вещи:
    блокировка запрещает `write` обеим сторонам, но оставляет `read` старой
    истории. Спроси сервис запись — и в тот день, когда появится блокировка,
    заблокированный не сможет сдвинуть собственный `last_read_seq`: квитанция
    отвергнется, непрочитанное зависнет, а на нём стоит `G3-003`. Отдельного
    действия под квитанцию (`ACK_CONVERSATION` и подобных) не заводится:
    правила для него в модели нет, решать по нему сегодня нечего, а появиться
    оно должно тогда, когда у квитанции будет собственное условие, отличное
    от условия чтения истории.

    Свежесть членства от смены действия не страдает: `membership_cache` не
    передаётся, а ветка кеша в `authorization._conversation` требует **обоих**
    условий — действия `READ` **и** непустого кеша. Соединение писателя плюс
    пустой кеш — членство всё равно читается из Postgres.

    Остаточный зазор — названный, а не закрытый: `validate_receipt_bound`
    сверяет присланное с головой беседы, то есть с «последним доступным»
    лишь до тех пор, пока всякий участник вправе прочитать беседу целиком.
    У бывшего участника доступ обрезан `left_at`, и там голова беседы
    перестаёт быть границей доступного; это условие того, кто введёт
    частичную историю, — сегодня `left_at` на чтение ещё не влияет.

    Блокировка сюда **не** относится, и сказано это не для полноты:
    `docs/messenger/08-authorization.md:96,100` разрешает обеим сторонам
    читать старую историю целиком — блокировка запрещает будущую запись,
    presence и typing, но прошлого не стирает. Именно ради этого квитанция
    и спрашивает право на чтение, а не на запись. Ограничивать её по
    времени блокировки значило бы отменить то самое решение.

    Голова читается соединением писателя, и это несущее условие, а не
    аккуратность. Проверка границы односторонняя (`≤ head`), голова не
    убывает, а номер `k` клиент узнаёт только из коммита, сделавшего `k`
    наблюдаемым, — поэтому отвергнуть честную квитанцию эта проверка не
    может. С отставшей реплики довод рассыпается: её `last_seq` меньше
    головы, и квитанция о только что полученном сообщении получила бы
    ложный отказ. Режим соединения здесь не выбирается намеренно — умолчание
    и есть писатель; если однажды появится соблазн увести запись в
    `STALE_OK`, этот абзац и есть ответ. По той же причине голова читается
    **до** транзакции: она односторонняя граница присланного, а не вход
    пересчёта, и держать на ней замок беседы значило бы платить за лишний
    запрос, притом на беседе, которая к моменту замка может уже не
    существовать (разбор — в докстринге модуля).

    Пересчёт проекции идёт **под замком** беседы и в том же порядке, что
    у потребителя: строка чекпойнта, затем строки проекции. Совпадение
    порядка делает взаимоблокировку невозможной, а сам замок закрывает
    гонку абсолютной записи с приращением.
    """
    validate_receipts(receipts)

    # Действие — чтение, а не запись: довод в докстринге, и он не про
    # строгость, а про то, что блокировка запрещает запись, но не чтение
    # старой истории. `membership_cache` не передаётся намеренно — свежесть
    # членства держится именно этим, а не выбором действия.
    decision = await authorization.authorize(
        conn,
        subject=Subject(viewer),
        resource=ResourceRef.conversation(conversation_id),
        action=Action.READ_CONVERSATION,
    )
    if not decision.allowed:
        return SetReceiptsResult(
            rejection=decision.reason or Reason.INTERNAL,
            visibility=decision.visibility,
        )

    head = await conversations.fetch_last_seq(conn, conversation_id=conversation_id)
    if head is None:
        # Беседа исчезла между решением о праве и чтением головы. Прежняя
        # редакция считала это недостижимым — «беседы ничто не удаляет», —
        # и живого прогона это не пережило: беседу удаляет уборка
        # интеграционной проверки, и удаляет вместе с производными
        # (каскад `0011`), а не вместе с чужими правами на неё. `None`
        # здесь сравнился бы с числом и уронил бы обработчик в `500`.
        return SetReceiptsResult(
            rejection=Reason.CONVERSATION_NOT_FOUND,
            visibility=decision.visibility,
        )

    validate_receipt_bound(receipts, head=head)
    state = state_of(receipts)

    # Транзакция начинается здесь, а не выше, и открывается ради замка,
    # а не ради атомарности одной записи: до этого места сервис только
    # читал, и держать транзакцию на проверках незачем.
    async with conn.transaction():
        # Замок чекпойнта — первым. Он фиксирует границу пересчёта: пока
        # он взят, потребитель не применит ни одного события беседы, и
        # `watermark` останется тем значением, по которому посчитано
        # записанное ниже число.
        watermark = await lock_offsets(conn, conversation_id=conversation_id)
        if watermark is None:
            # Беседа исчезла между чтением головы и замком — та же гонка,
            # что названа выше, но на шаг позже. Ответ тот же, и он
            # не исключение: чекпойнта у удалённой беседы не остаётся
            # (каскад `0011`), поэтому `None` от замка значит ровно
            # «беседы нет», а не «замок не взялся».
            return SetReceiptsResult(
                rejection=Reason.CONVERSATION_NOT_FOUND,
                visibility=decision.visibility,
            )
        stored = await read_states.upsert_read_state(
            conn,
            conversation_id=conversation_id,
            user_id=viewer.user_id,
            delivered_seq=state.delivered_seq,
            read_seq=state.read_seq,
        )
        # Нижняя граница — `stored.read_seq`, а не присланное: два
        # устройства одного пользователя пишут в одну строку, и
        # проигравшее обязано пересчитаться по тому, что в ней лежит.
        count = await recount_unread(
            conn,
            conversation_id=conversation_id,
            user_id=viewer.user_id,
            above_seq=stored.read_seq,
            through_seq=watermark,
        )
    return SetReceiptsResult(state=stored, unread_count=count)
